# -*- coding: utf-8 -*-
"""Как назвать нашу работу Semantic Scholar'у: ARXIV — не единственный ключ.

ЗАЧЕМ ЭТОТ ФАЙЛ. Все наши обращения к S2 строили идентификатор одинаково — `ARXIV:<номер>`.
Для работ с arXiv это верно и работает. Но с 12.09.2026 в архиве есть работы не из arXiv:
препринты bioRxiv и medRxiv со своими номерами вида 2609.900NN. Для S2 такой номер —
пустое место: `ARXIV:2609.90039` не существует, ответ приходит пустой, и работа молча
выпадает из всего, что построено на S2.

ЧТО ИМЕННО ТЕРЯЛОСЬ (замер 15.09.2026):
  · наших био/мед работ в собранном S2 — 0 из 129;
  · 1233 автора этих работ остались без authorId, то есть вне механизма развода
    однофамильцев (tools/s2_authors.py): под ключом «фамилия+инициалы» слипаются
    разные люди, и разводит их именно ребро S2 «работа → автор»;
  · цитатный граф этих работ пуст.

ПОЧЕМУ ЧИНИТСЯ ПРОСТО. У каждой такой работы есть НАСТОЯЩИЙ DOI, и S2 принимает его тем
же ключом в той же пакетной ручке: `DOI:10.1101/...`. Проба 15.09: шесть работ из шести
нашлись, у всех — полный список авторов с идентификаторами. То есть ни новых запросов,
ни новой механики не нужно, нужно лишь назвать работу так, как её знает S2.

Правило здесь одно на всех, чтобы третий инструмент не забыли снова.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
_VER = re.compile(r"v\d+$")
_DOIS = None


def bare(aid):
    """Номер без версии: S2 знает предмет, а не редакцию."""
    return _VER.sub("", str(aid or "").strip())


def doi_map():
    """{номер работы: DOI} для работ, у которых DOI свой, а не выводится из номера.

    Читаем архив, а не папку приёма: в архиве лежит то, что реально опубликовано, и
    поле sources.doi туда кладёт тот же код, что строит страницу.
    """
    global _DOIS
    if _DOIS is not None:
        return _DOIS
    out = {}
    for p in (ROOT / "lang" / "ru" / "archive").glob("*/*/data.json"):
        try:
            d = json.loads(p.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        doi = (d.get("sources") or {}).get("doi")
        if doi:
            out[bare(p.parent.name)] = str(doi).strip()
    _DOIS = out
    return out


def s2_id(aid):
    """Идентификатор работы для S2: DOI, если он у неё свой, иначе arXiv."""
    b = bare(aid)
    doi = doi_map().get(b)
    return f"DOI:{doi}" if doi else f"ARXIV:{b}"


def s2_ids(aids):
    """То же пачкой — порядок сохраняется, он важен: ответ S2 сопоставляют по позиции."""
    return [s2_id(a) for a in aids]
