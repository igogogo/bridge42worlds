def lessons(topic):
    out = []
    for f in sorted((ROOT / topic).glob("*.json")):
        if f.name in ("course.json", "guide.json"):
            continue
        out.append((f, json.loads(f.read_text(encoding="utf-8"))))
    return out


def site_names():
    """Названия законов и тегов по-русски — из справочников сайта, если он рядом.

    Иначе в путеводителе стояло бы «boltzmann distribution» и «thermal conductivity»:
    идентификаторы читаемы для машины, а страница у нас для человека.
    """
    base = Path("..") / "bridge42worlds" / "lang" / "ru" / "data"
    out = {"law": {}, "tag": {}}
    try:
        laws = json.loads((base / "laws-lite.json").read_text(encoding="utf-8"))
        for k, v in laws.items():
            n = (v or {}).get("name")
            if n:
                out["law"][k] = n
    except Exception:
        pass
    try:
        tags = json.loads((base / "tags-list.json").read_text(encoding="utf-8"))
        for t in tags:
            if isinstance(t, dict) and t.get("en") and t.get("ru"):
                out["tag"][t["en"]] = t["ru"]
    except Exception:
        pass
    return out


NAMES = site_names()


def hours(rows):
    """Часы по самой таблице бюджета, а не по памяти автора.

    Раньше подводка обещала «3–4 часа», а строки ниже давали 3,5–4,5 — читатель видел
    оба числа на одном экране. Считаем из строк: они собраны из настоящих параграфов.
    """
    lo = hi = 0
    for r in rows:
        nums = [int(x) for x in re.findall(r"[0-9]+", r.get("time", ""))]
        if not nums:
            continue
        lo += nums[0]
        hi += nums[-1]

    def fmt(minutes):
        h = minutes / 60.0
        h = round(h * 2) / 2                       # до получаса: точнее обещать нечестно
        return ("%.1f" % h).replace(".0", "").replace(".", ",")

    a, b = fmt(lo), fmt(hi)
    tail = "часа" if ("," in b or b in ("2", "3", "4")) else "часов"
    return "%s–%s %s" % (a, b, tail)


def topic_title(tid):
    """Название темы по-русски: «Механика», а не mechanics."""
    f = ROOT / tid / "course.json"
    if f.exists():
        try:
            return json.loads(f.read_text(encoding="utf-8"))["ru"]["title"]
        except Exception:
            pass
    return tid


def build(topic, sample, node):
    ls = lessons(topic)
    a = TOPICS[topic]

    rows = [{"what": "Обзорная глава", "time": "15–20 мин",
             "note": "читается один раз, без формул — задаёт контекст"}]
    for i, (_, d) in enumerate(ls, 1):
        rows.append({"what": f"Параграф {i} · {d['ru'].get('title', '')}",
                     "time": "60–80 мин",
                     "note": "стенд, вывод формулы и проверка знаний"})
    rows.append({"what": "Итоговая проверка", "time": "15 мин",
                 "note": "вопросы на понимание, не на память"})

    experiments = []
    for i, (_, d) in enumerate(ls, 1):
        for it in (d["ru"].get("curiosities") or {}).get("items", []):
            if "кухн" in (it.get("kind") or ""):
                first = re.split(r"(?<=[.!?])\s", (it.get("text") or "").strip())
                experiments.append({"p": str(i), "what": it.get("h", ""),
                                    "how": (first[0].strip() if first else "") + " …"})

    # Имя закона берём из формулы урока — там оно человеческое («Второй закон Ньютона»),
    # а не машинное из идентификатора. Заодно отмечаем, в каком параграфе закон разбирается.
    laws, sci, seen_l, seen_s = [], [], set(), set()
    for i, (_, d) in enumerate(ls, 1):
        ent = d.get("entities") or {}
        fname = ((d["ru"].get("formula") or {}).get("name") or "").strip()
        for j, lid in enumerate(ent.get("laws") or []):
            if lid in seen_l:
                continue
            seen_l.add(lid)
            # Имя формулы подставляем ТОЛЬКО когда закон у параграфа один: иначе первому
            # в списке доставалось чужое имя, и в путеводителе выходило «ficks_law —
            # Формула Эйнштейна — Смолуховского» (находка сверки).
            single = len(ent.get("laws") or []) == 1
            laws.append({"id": lid,
                         "name": (fname if (single and fname)
                                  else NAMES["law"].get(lid) or lid.replace("_", " ")),
                         "note": f"разбирается в параграфе {i}"})
        for s in ent.get("scientists") or []:
            if s not in seen_s:
                seen_s.add(s)
                # id страницы учёного — имя с подчёркиваниями, как в базе сайта
                sci.append({"id": s.replace(" ", "_"), "name": s})

    tags, seen_t = [], set()
    for _, d in ls:
        for t in (d.get("entities") or {}).get("tags") or []:
            if t not in seen_t:
                seen_t.add(t)
                tags.append({"id": t, "name": NAMES["tag"].get(t) or t.replace("_", " ")})

    # Общая часть «как проходить» берётся у термодинамики, но пример в шаге про константы
    # там свой, термодинамический (джоуль на кельвин против джоуля на моль-кельвин).
    # Для остальных тем ставим формулировку без привязки к веществу.
    howto = copy.deepcopy(sample["howto"])
    if topic != "thermodynamics":
        for st in howto.get("steps", []):
            if "констант" in st.get("what", "").lower():
                st["how"] = ("Не заучивайте числа — поймите, что означает каждая единица "
                             "измерения: из записи единицы обычно видно, как величина устроена "
                             "и на что её надо умножать. Мнемоники под каждой константой — "
                             "для тех, кому всё-таки нужно запомнить цифру.")

    needs = node.get("needs") or []
    level_text = [a["level"]]
    if needs:
        level_text.append("Темы, на которые опирается этот материал: " +
                          ", ".join(topic_title(n) for n in needs) +
                          ". Если они не пройдены, часть выводов будет держаться на честном слове.")
    if node.get("open"):
        level_text.append("Честно о границе: в этой теме до сих пор не решено — " + node["open"] + ".")

    guide = {
        "title": "Как работать с этим материалом",
        "subtitle": "Методичка для самостоятельного изучения",
        "lead": a["lead"],
        "budget": {"title": "Сколько это займёт",
                   "lead": "Тема рассчитана примерно на " + hours(rows) + " вдумчивой работы. "
                           "Это не «прочитать за вечер»: при быстром чтении материал не "
                           "удерживается. Разумный ритм — один параграф за подход.",
                   "rows": rows,
                   "note": "Если на параграф уходит вдвое больше — это нормально и даже хорошо. "
                           "Плохо обратное: пробежать за двадцать минут и решить, что понятно."},
        "level": {"title": "На кого рассчитан", "text": level_text},
        "howto": howto,
        "stuck": sample["stuck"],
        "experiments": {"title": "Опыты, которые стоит проделать",
                        "lead": "Каждый занимает несколько минут и не требует ничего, кроме кухни. "
                                "Это не украшение курса — именно они превращают прочитанное в понятое.",
                        "items": experiments},
        "next": {"title": "Куда двигаться после темы", "items": a["nxt"]},
    }
    # Пустой раздел лучше не показывать вовсе: часть уроков ещё не связана с базой сайта
    # (отдельная задача), и «Материалы по теме» без единой ссылки выглядели бы поломкой.
    if laws or sci or tags:
        guide["library"] = {"title": "Материалы по теме на сайте",
                            "lead": "Курс не изолирован: законы и учёные, упомянутые здесь, имеют "
                                    "собственные страницы в нашей базе — с формулами, связями и "
                                    "статьями, где этот закон работает на практике.",
                            "laws": laws, "scientists": sci, "tags": tags}
    return guide


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--force", action="store_true", help="пересобрать русскую ветку поверх готовых")
    args = ap.parse_args()

    sample = json.loads(SAMPLE.read_text(encoding="utf-8"))["ru"]
    index = json.loads((ROOT / "index.json").read_text(encoding="utf-8"))
    nodes = {t["id"]: t for t in index["topics"]}

    made = 0
    for topic in TOPICS:
        out = ROOT / topic / "guide.json"
        if out.exists() and not args.force:
            print(f"  {topic}: уже есть, пропуск")
            continue
        ru = build(topic, sample, nodes.get(topic, {}))
        doc = {"id": "guide", "topic": topic, "schema": "b42.guide/1", "kind": "guide", "ru": ru}
        if out.exists():
            # Пересобираем русскую ветку, переводы оставляем на месте: устаревшие снимет
            # tools/retranslate_stale.py, а свежие незачем переводить заново.
            old_doc = json.loads(out.read_text(encoding="utf-8"))
            for k, v in old_doc.items():
                if k not in doc:
                    doc[k] = v
        print(f"  {topic}: параграфов {len(ru['budget']['rows']) - 2}, "
              f"опытов {len(ru['experiments']['items'])}, законов {len(ru['library']['laws'])}")
        if not args.check:
            out.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
            made += 1
    print(("собрано бы" if args.check else "записано") + f": {made or len(TOPICS)} путеводителей")
    return 0


if __name__ == "__main__":
    sys.exit(main())
