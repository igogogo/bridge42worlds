def lessons(topic):
    out = []
    for f in sorted((ROOT / topic).glob("*.json")):
        if f.name in ("course.json", "guide.json"):
            continue
        out.append((f, json.loads(f.read_text(encoding="utf-8"))))
    return out


def build(topic, sample, node):
    ls = lessons(topic)
    a = TOPICS[topic]

    rows = [{"what": "Обзорная глава", "time": "15–20 мин",
             "note": "читается один раз, без формул — задаёт контекст"}]
    for i, (_, d) in enumerate(ls, 1):
        rows.append({"what": f"Параграф {i} · {d['ru'].get('title', '')}",
                     "time": "60–80 мин",
                     "note": "стенд, вывод формулы и проверка знаний"})
    rows.append({"what": "Итоговая проверка", "time": "15 мин",
                 "note": "вопросы на понимание, не на память"})

    experiments = []
    for i, (_, d) in enumerate(ls, 1):
        for it in (d["ru"].get("curiosities") or {}).get("items", []):
            if "кухн" in (it.get("kind") or ""):
                experiments.append({"p": str(i), "what": it.get("h", ""),
                                    "why": (it.get("text") or "").split(".")[0].strip() + "."})

    # Имя закона берём из формулы урока — там оно человеческое («Второй закон Ньютона»),
    # а не машинное из идентификатора. Заодно отмечаем, в каком параграфе закон разбирается.
    laws, sci, seen_l, seen_s = [], [], set(), set()
    for i, (_, d) in enumerate(ls, 1):
        ent = d.get("entities") or {}
        fname = ((d["ru"].get("formula") or {}).get("name") or "").strip()
        for j, lid in enumerate(ent.get("laws") or []):
            if lid in seen_l:
                continue
            seen_l.add(lid)
            laws.append({"id": lid,
                         "name": fname if (j == 0 and fname) else lid.replace("_", " "),
                         "note": f"разбирается в параграфе {i}"})
        for s in ent.get("scientists") or []:
            if s not in seen_s:
                seen_s.add(s)
                # id страницы учёного — имя с подчёркиваниями, как в базе сайта
                sci.append({"id": s.replace(" ", "_"), "name": s})

    tags, seen_t = [], set()
    for _, d in ls:
        for t in (d.get("entities") or {}).get("tags") or []:
            if t not in seen_t:
                seen_t.add(t)
                tags.append({"id": t, "name": t.replace("_", " ")})

    needs = node.get("needs") or []
    level_text = [a["level"]]
    if needs:
        level_text.append("Темы, на которые опирается этот материал: " + ", ".join(needs) +
                          ". Если они не пройдены, часть выводов будет держаться на честном слове.")
    if node.get("open"):
        level_text.append("Честно о границе: в этой теме до сих пор не решено — " + node["open"] + ".")

    guide = {
        "title": "Как работать с этим материалом",
        "subtitle": "Методичка для самостоятельного изучения",
        "lead": a["lead"],
        "budget": {"title": "Сколько это займёт",
                   "lead": "Тема рассчитана примерно на 3–4 часа вдумчивой работы. Это не «прочитать "
                           "за вечер»: при быстром чтении материал не удерживается. Разумный ритм — "
                           "один параграф за подход.",
                   "rows": rows,
                   "note": "Если на параграф уходит вдвое больше — это нормально и даже хорошо. "
                           "Плохо обратное: пробежать за двадцать минут и решить, что понятно."},
        "level": {"title": "На кого рассчитан", "text": level_text},
        "howto": sample["howto"],
        "stuck": sample["stuck"],
        "experiments": {"title": "Опыты, которые стоит проделать",
                        "lead": "Каждый занимает несколько минут и не требует ничего, кроме кухни. "
                                "Это не украшение курса — именно они превращают прочитанное в понятое.",
                        "items": experiments},
        "next": {"title": "Куда двигаться после темы", "items": a["nxt"]},
    }
    # Пустой раздел лучше не показывать вовсе: часть уроков ещё не связана с базой сайта
    # (отдельная задача), и «Материалы по теме» без единой ссылки выглядели бы поломкой.
    if laws or sci or tags:
        guide["library"] = {"title": "Материалы по теме на сайте",
                            "lead": "Курс не изолирован: законы и учёные, упомянутые здесь, имеют "
                                    "собственные страницы в нашей базе — с формулами, связями и "
                                    "статьями, где этот закон работает на практике.",
                            "laws": laws, "scientists": sci, "tags": tags}
    return guide


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    sample = json.loads(SAMPLE.read_text(encoding="utf-8"))["ru"]
    index = json.loads((ROOT / "index.json").read_text(encoding="utf-8"))
    nodes = {t["id"]: t for t in index["topics"]}

    made = 0
    for topic in TOPICS:
        out = ROOT / topic / "guide.json"
        if out.exists():
            print(f"  {topic}: уже есть, пропуск")
            continue
        ru = build(topic, sample, nodes.get(topic, {}))
        doc = {"id": "guide", "topic": topic, "schema": "b42.guide/1", "kind": "guide", "ru": ru}
        print(f"  {topic}: параграфов {len(ru['budget']['rows']) - 2}, "
              f"опытов {len(ru['experiments']['items'])}, законов {len(ru['library']['laws'])}")
        if not args.check:
            out.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
            made += 1
    print(("собрано бы" if args.check else "записано") + f": {made or len(TOPICS)} путеводителей")
    return 0


if __name__ == "__main__":
    sys.exit(main())
