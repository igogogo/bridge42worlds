#!/bin/bash
# Точечный прогон: забрать дни, собрать изменившееся, выложить. Ничего больше.
# Владелец 28.08: «переводы, прочее — это всё потом; давай прогони, чтобы новые
# дни появились, и стоп».
#
# После КАЖДОГО дня отмечаемся в журнале схемы (/pipeline.html). Иначе она
# показывает последнее, что ей сообщили, и прогон выглядит зависшим — так и
# случилось 28.08: конвейер шёл, а схема час стояла на одном дне.
set -u
cd "$(dirname "$0")/.."
export B42_LEAD=1 PYTHONIOENCODING=utf-8
DAYS="${1:-2026-08-24,2026-08-25,2026-08-26,2026-08-27}"
IFS=',' read -ra LIST <<< "$DAYS"
for d in "${LIST[@]}"; do
  echo "═══ день $d ═══"
  python tools/days_state.py --days "$DAYS" --current "day-$d" >/dev/null 2>&1
  B42_LANGS=ru,en B42_NO_PUBLISH=1 python run.py daily --date "$d" --limit 20
  python tools/days_state.py --days "$DAYS" >/dev/null 2>&1
done
# ПОРЯДОК: сначала разметка, потом сборка. Вчера было наоборот, и страницы
# собирались из данных, которых ещё не было, — статья выходила без понятий,
# а после разметки её никто не пересобирал (владелец 29.08, со ссылкой на статью).
#
# РАЗМЕТКА И ПОДСВЕТКА — ТОЧЕЧНО, ПО СТАТЬЯМ ДНЯ. Я отправил оба шага в недельный
# прогон по признаку «обходит весь архив». Признак был выбран неверно: считать надо
# не «сколько шаг обходит», а «нужно ли это новой статье сегодня». Оба инструмента
# умеют работать по списку — этим и пользуемся, а по всему архиву они по-прежнему
# ходят только в служебном прогоне.
echo "═══ разметка понятиями (статьи дня) ═══"
IDS=""
for d in "${LIST[@]}"; do
  for f in lang/ru/archive/"$d"/*/; do
    [ -d "$f" ] && IDS="$IDS,$(basename "$f")"
  done
done
IDS="${IDS#,}"
if [ -n "$IDS" ]; then
  # ВЕКТОР СВЕЖЕЙ СТАТЬИ. Выгрузка arXiv отстаёт на недели, и работы последних дней
  # в ней отсутствуют; без вектора разметка честно отвечает «статьи нет в корпусе»
  # и статья выходит без единого понятия. Тексты берём из наших же data.json.
  MONTH=$(date -d "${LIST[0]}" +%Y-%m 2>/dev/null || echo "")
  (cd ../b42-ml && python field_build.py --ours ${MONTH:+--months "$MONTH"} --max-cost 0.5)
  python tools/retag_hub.py --live "$IDS" --apply --thr 0.50 --margin 0.12
  # Разметка лежит предложением в отдельном файле; в данные статей её вносит этот шаг.
  # --articles-only: справочник понятий не перезаписываем — над живым файлом уже
  # поработали слияния двойников и переводы названий, дню это ни к чему.
  python tools/wave5_apply.py --apply --articles-only
  echo "═══ подсветка терминов (статьи дня) ═══"
  python tools/highlight_concepts.py --tiers simple,popular,advanced --ids "$IDS"
fi

echo "═══ сборка дней ═══"
python tools/days_state.py --days "$DAYS" --current html >/dev/null 2>&1
# --only СПИСКОМ ДНЕЙ, а не «всё изменившееся». Разница видна на примере: 29.08
# веник по тире тронул данные 5 807 статей, и обычный отбор по отпечаткам
# потянул бы их все — тридцать пять тысяч страниц вместо восьми статей дня.
# Узкий прогон обязан собирать РОВНО свои дни; всё прочее — служебный прогон
# (tools/weekly_run.py), и о нём говорят вслух. Отпечатки при --only не
# переписываются (см. generate.py), поэтому список несобранного не теряется.
B42_LANGS=ru,en B42_NO_PUBLISH=1 python run.py html --only "${LIST[@]}"

# Карточки статей в облачную базу: страница статьи уезжает статикой в R2, а ЛЕНТА
# собирается из D1. Без этого шага статья открывается по прямой ссылке, но в ленте
# её нет — 28.08 так и вышло, и выглядело это как «динамика не работает».
echo "═══ карточки в облако ═══"
python cloudflare/cards_sync.py --apply

echo "═══ выкладка ═══"
python tools/days_state.py --days "$DAYS" --current publish >/dev/null 2>&1
python run.py publish
python tools/days_state.py --days "$DAYS" --finish >/dev/null 2>&1
echo "═══ готово ═══"
