def show_plan():
    money, bal, left_day = purse()
    steps, c, gaps = plan(money)
    print(f"\n💳 на счету DeepSeek: {'—' if bal is None else f'${bal:.2f}'}"
          f" · дневной остаток ${left_day:.2f} · к работе ${money:.2f}")
    print(f"📦 в архиве: {c['полных']} полных, {c['экспрессов']} экспрессов, "
          f"{c['с советами']} с советами (долг {c['полных без советов']})")
    if gaps:
        print(f"📅 тощие дни: {', '.join(f'{d} ({n})' for d, n in gaps[:6])}")
    else:
        print("📅 дни закрыты")
    print("\nПЛАН:")
    total = 0.0
    for s in steps:
        total += s["cost"]
        print(f"  {s['key']:9} {s['title']:44} "
              f"{'—' if not s['n'] else s['n']:>4}  ~${s['cost']:.2f}")
    print(f"  {'ИТОГО':9} {'':44} {'':>4}  ~${total:.2f}")
    if money < 0.05:
        print("\n🔴 денег нет — прогон только пересоберёт сайт и отчитается")
    return steps


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", action="store_true", help="показать план и выйти")
    ap.add_argument("--only", help="выполнить один шаг: days/advise/upgrade/weekly_full/"
                                   "uplift/research/orders/related/points/analytics/graph/tech")
    ap.add_argument("--no-publish", action="store_true", help="не пересобирать и не выкладывать")
    args = ap.parse_args()

    if args.plan:
        show_plan()
        return 0

    steps = show_plan()
    if args.only:
        steps = [s for s in steps if s["key"] == args.only]
        if not steps:
            print(f"шаг «{args.only}» сегодня не запланирован")
            return 0

    # Расход на входе — чтобы в отчёте назвать цену ИМЕННО этого прогона, а не всего дня.
    started_spent = spent_today()
    print("\n▶️ работаем")
    done = []
    for s in steps:
        money, _bal, _ = purse()
        if s["cost"] > 0 and money < s["cost"] * 0.5:
            print(f"  ⏭️ {s['key']}: денег осталось ${money:.2f} — пропускаю")
            continue
        rc = do_step(s)
        done.append((s["key"], rc))

    if not args.no_publish:
        print("\n▶️ пересборка и выкладка")
        rc = run([sys.executable, "run.py", "html"], timeout=21600)
        done.append(("publish", rc))
        # Карточки в D1 — СРАЗУ после пересборки индексов: с 25 августа лента, страницы
        # авторов и поиск словами читаются оттуда, а не из articles-index*.json. Пропущенная
        # синхронизация означает не поломку, а вещь худшую — сайт, который тихо показывает
        # вчерашний архив. Ровно это и случилось с базой b42-cards: её подняли 6 августа,
        # залили треть архива и не поставили в расписание — девятнадцать дней она стояла
        # с данными, которых никто не читал и никто не хватился.
        # Заливается только разница по отпечатку строки, обычный день — десятки строк.
        rc = run([sys.executable, "cloudflare/cards_sync.py", "--apply"], timeout=5400)
        done.append(("cards", rc))
        # Обвязка — связи тег/закон/учёный/раздел → работа, сводки сущностей, «бока»
        # статей. Тот же принцип, что у карточек: сайт читает это из D1, значит после
        # каждой пересборки индексов данные обязаны доехать до облака сами, а не когда
        # вспомнят. Девятнадцать дней мёртвой b42-cards выучены.
        rc = run([sys.executable, "cloudflare/frame_sync.py", "--apply"], timeout=5400)
        done.append(("frame", rc))
        run([sys.executable, "tools/stats_refresh.py"], timeout=1800)

    STATE.parent.mkdir(exist_ok=True)
    spent = max(0.0, spent_today() - started_spent)
    STATE.write_text(json.dumps({"когда": datetime.now().isoformat(timespec="minutes"),
                                 "шаги": done, "потрачено": round(spent, 3),
                                 "план": [s["key"] for s in steps]},
                                ensure_ascii=False, indent=1), encoding="utf-8")
    bad = [k for k, rc in done if rc not in (0, None)]
    print(f"\n{'⚠️' if bad else '✅'} готово: {', '.join(k for k, _ in done)}"
          + (f" · споткнулись: {', '.join(bad)}" if bad else ""))
    report(done, bad, spent)
    return 0


