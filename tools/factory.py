def report(done, bad, spent):
    """Одно сообщение в канал: что фабрика сделала сегодня и во что это обошлось.

    Без него прогон бессловесен: лог лежит в файле, который никто не открывает, а о
    работе конвейера владелец узнаёт по тому, появились ли новые статьи. Отчёт уходит
    в любом случае — «денег не было, сделали бесплатное» это тоже новость, и хорошая:
    значит автомат жив.

    Текст передаём ФАЙЛОМ, а не аргументом: консоль Windows отдаёт аргументы в OEM-
    кодировке, и русские слова уже приезжали в канал кракозябрами (владелец поймал
    это 4 августа).
    """
    ok = [STEP_NAMES.get(k, k) for k, rc in done if rc in (0, None)]
    fail = [STEP_NAMES.get(k, k) for k in bad]
    bal = balance()
    lines = ["🏭 <b>Фабрика отработала</b>",
             "Сделано: " + (", ".join(ok) if ok else "ничего")]
    if fail:
        lines.append("⚠️ Споткнулись: " + ", ".join(fail))
    lines.append(f"Потрачено за прогон: ${spent:.2f}"
                 + (f" · на счету осталось ${bal:.2f}" if bal is not None else ""))
    if bal is not None and bal < 1.0:
        lines.append("🔴 Денег почти нет. Завтра фабрика сделает бесплатное: аналитику, "
                     "граф, дашборд и точки схождения — конвейер не встанет.")
    try:
        msg = LOGS / "factory-report.txt"
        msg.write_text("\n".join(lines), encoding="utf-8")
        # В канал — только когда случилось то, на что надо реагировать: сбой шага или
        # кончающиеся деньги. Штатный «фабрика отработала» уходит в файл, откуда его
        # берёт утренний отчёт (владелец 2026-08-24: «в канал идёт очень много сообщений»;
        # правило — ежедневный полный отчёт в 4 утра, немедленно только критичное).
        critical = any(("Споткнулись" in l) or ("🔴" in l) for l in lines)
        if critical:
            subprocess.run([sys.executable, str(ROOT / "tools" / "status_tg.py"),
                            "--file", str(msg)], cwd=ROOT, timeout=120,
                           env={**os.environ, "PYTHONIOENCODING": "utf-8"})
    except Exception as ex:
        print(f"⚠️ отчёт в канал не ушёл: {type(ex).__name__}")


def do_step(s):
    """Один шаг фабрики. Каждый — существующий инструмент, а не новая логика."""
    k = s["key"]
    if k == "orders":
        # Без флагов = ровно один проход по очереди (queue_worker.__main__): --loop
        # крутится вечно, --dry ничего не делает. Флага --once там нет и не было.
        return run([sys.executable, "cloudflare/queue_worker.py"], timeout=3600)
    if k == "days":
        rc = 0
        for d, _n in s["days"]:
            rc = run([sys.executable, "run.py", "range", "--from", d, "--to", d,
                      "--express", "--limit", str(max(5, s["n"] // max(1, len(s["days"])))),
                      "--category", CATEGORIES],
                     timeout=7200) or rc
        return rc
    if k == "uplift":
        # Дотяжка «Популярно» до честного второго уровня + перевод поднятого на арабский.
        # Аудит 16 августа: однократная дотяжка воспроизвела долг за неделю — шаг обязан
        # жить в плане каждый день, а перевод идти тем же проходом, не отдельной задачей.
        return run([sys.executable, "tools/express_uplift.py", "--pilot", str(s["n"]),
                    "--translate", "ar"], timeout=7200)
    if k in ("upgrade", "weekly_full"):
        # Доращиваем экспресс до полного разбора. B42_NO_PUBLISH=1 — иначе run.py regen
        # публикует сайт после КАЖДОЙ статьи: пять апгрейдов это пять полных выкаток
        # в R2 подряд. Выкладка одна, в конце прогона.
        #
        # Переменная тут появилась 18.08: раньше её обещал вот этот комментарий, а код
        # её не ставил — run() просто не умела передавать окружение. На трёх статьях в
        # день это стоило трёх лишних выкладок, на двенадцати недельных стоило бы
        # двенадцати. Комментарий, который расходится с кодом, хуже отсутствующего:
        # следующий читает его и считает вопрос закрытым.
        rc = 0
        started = time.time()
        for aid in s.get("ids", []):
            # Свой потолок времени на статью и общий на шаг. При прежних 5400 с на статью
            # двенадцать штук в худшем случае держали бы прогон 18 часов, а следом идёт
            # выкладка со своим таймаутом — фабрика не успела бы к следующему запуску.
            if time.time() - started > WEEKLY_FULL_BUDGET_S:
                # Остаток отложен ПО ПЛАНУ, это не сбой: лимит на шаг и существует для
                # того, чтобы длинные разборы не съели прогон. Возвращать здесь ненулевой
                # код нельзя — отчёт писал «споткнулись: weekly_full», владелец читал это
                # как ошибку (17 августа) и шёл разбираться в здоровый механизм. Отложенные
                # статьи возьмёт следующий понедельник.
                print(f"⏱️ {k}: лимит времени шага исчерпан — остаток отложен до следующей "
                      f"недели (это план, не сбой)", flush=True)
