// 4. Разрез капли: натяжение по окружности против избыточного давления
F.realdrop = function () {
    var W = 460, H = 215, cx = 160, cy = 112, R = 74;
    var s = txt(W / 2, 18, 'половинка капли в равновесии', SOFT, 11);

    s += '<path d="M' + (cx - R) + ',' + cy + ' A' + R + ',' + R + ' 0 0 1 ' + (cx + R) + ',' + cy +
         ' Z" fill="' + LINK + '" opacity="0.16" stroke="' + LINK + '" stroke-width="2"/>';
    s += '<path d="M' + (cx - R) + ',' + cy + ' A' + R + ',' + R + ' 0 0 0 ' + (cx + R) + ',' + cy +
         '" fill="none" stroke="' + SOFT + '" stroke-width="1.4" stroke-dasharray="5,4"/>';
    s += '<line x1="' + (cx - R - 18) + '" y1="' + cy + '" x2="' + (cx + R + 18) + '" y2="' + cy +
         '" stroke="' + INK + '" stroke-width="1.4" stroke-dasharray="6,4"/>';

    /* давление изнутри — радиальные стрелки вверх-наружу */
    var i, a;
    for (i = 0; i < 5; i++) {
        a = Math.PI + Math.PI * (0.16 + 0.17 * i);
        s += arrow(cx + 0.30 * R * Math.cos(a), cy + 0.30 * R * Math.sin(a),
                   cx + 0.80 * R * Math.cos(a), cy + 0.80 * R * Math.sin(a), WARN, 'ahw');
    }
    s += txt(cx, cy - 28, '&#916;p', WARN, 14);

    /* натяжение по линии разреза — тянет половинки друг к другу */
    s += arrow(cx - R - 4, cy - 12, cx - R + 40, cy - 12, INK);
    s += arrow(cx + R + 4, cy - 12, cx + R - 40, cy - 12, INK);
    s += txt(cx - R - 6, cy - 22, '&#963;', INK, 13, 'middle');
    s += txt(cx + R + 6, cy - 22, '&#963;', INK, 13, 'middle');

    s += arrow(cx, cy, cx + R * 0.70, cy - R * 0.70, SOFT);
    s += txt(cx + 44, cy - 54, 'R', SOFT, 13);

    s += txt(340, 74, 'давление изнутри:', SOFT, 11);
    s += txt(340, 92, '&#916;p &#183; &#960;R&#178;', WARN, 13);
    s += txt(340, 118, 'натяжение по разрезу:', SOFT, 11);
    s += txt(340, 136, '&#963; &#183; 2&#960;R', INK, 13);
    s += '<line x1="278" y1="152" x2="418" y2="152" stroke="' + BORD + '"/>';
    s += txt(340, 174, '&#916;p = 2&#963;/R', INK, 15);
    s += txt(W / 2, H - 6, 'R = 1 мкм &#8658; 146 кПа, почти полторы атмосферы', SOFT, 11);
    return svg(W, H, s);
};

