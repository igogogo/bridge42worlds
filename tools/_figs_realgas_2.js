/* _figs_realgas_2.js — ЗАГОТОВКА схем для realgas/02-surface
   («Поверхностное натяжение и капилляры»).

   Это НЕ модуль: здесь только тела функций в стиле js/figures.js.
   Ведущая сессия вклеивает их внутрь IIFE файла js/figures.js, где уже определены
   помощники svg(), txt(), arrow(), mol(), wall() и цвета INK, SOFT, LINK, WARN, BORD, MOSS.
   Все словесные подписи идут через txt() (то есть через label()) — словарь для
   js/figures-i18n.js выписан списком в конце файла.

   Восемь схем — по одной на каждый шаг вывода:
     realneigh — молекуле на границе не хватает соседей
     realarea  — оценка σ из теплоты испарения
     realframe — рамка с подвижной перекладиной: Дж/м² = Н/м
     realdrop  — разрез капли: Δp = 2σ/R
     realbubble— у плёнки две поверхности: Δp = 4σ/R
     realwet   — три натяжения на линии контакта, краевой угол
     realcap   — подъём в трубке: вес столба против натяжения по периметру
     realtree  — предел капилляра и нанопоры листа
*/

// 1. Молекула внутри и молекула на границе: половины соседей нет
