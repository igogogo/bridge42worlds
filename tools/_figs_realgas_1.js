/* _figs_realgas_1.js — ЗАГОТОВКА схем к параграфу realgas/01-vanderwaals.
   Восемь функций F.realgap … F.realsuper плюс два общих помощника.

   КАК ВКЛЕИВАТЬ (для ведущей сессии). Файл не модуль: он написан так, чтобы его тело
   целиком легло внутрь IIFE js/figures.js — там уже объявлены svg(), txt(), arrow(), mol(),
   wall() и цвета INK/SOFT/LINK/WARN/BORD/MOSS, и здесь они не переопределяются. Два
   помощника (vdwRed и rgPath) названы с префиксом, чтобы не столкнуться с mxPath и прочим.

   ЯЗЫК. Все словесные подписи внутри схем идут через txt() и потому проходят через label();
   полный их список — комментарием в самом конце файла, его надо перенести в js/figures-i18n.js.

   ЧИСЛА. Опорная кривая Z(p) для CO₂ при 20 °C пересчитана по двум независимым
   корреляциям (Пенг — Робинсон и Ли — Кеслер, расхождение меньше процента): при 1 бар
   0,994, при 10 — 0,942, при 40 — 0,731. Остальные кривые считаются по приведённому
   уравнению Ван-дер-Ваальса
   p/p_c = 8(T/T_c)/(3V/V_c − 1) − 3/(V/V_c)², то есть рисуются, а не подгоняются на глаз.
   Числа площадки при T/T_c = 0,90 посчитаны правилом равных площадей и проверены:
   p_s = 0,647, V_l = 0,603, V_g = 2,35, средний корень V_m = 1,09;
   интеграл 1,1301 против p_s·(V_g − V_l) = 1,1301. */

    /* Приведённое уравнение Ван-дер-Ваальса: одна кривая на все вещества сразу. */
    function vdwRed(Tr, Vr) { return 8 * Tr / (3 * Vr - 1) - 3 / (Vr * Vr); }

    /* Ломаная по функции с обрезкой по вертикали: точки вне окна не рисуются, а рвут линию,
       иначе изотерма при малом V уходит в бесконечность и утаскивает за собой всю картинку.
       SX/SY — готовые преобразования мир→экран, fn(v) возвращает значение или null. */
    function rgPath(v0, v1, n, fn, SX, SY, lo, hi) {
        var d = '', pen = false;
        for (var i = 0; i <= n; i++) {
            var v = v0 + (v1 - v0) * i / n, y = fn(v);
            if (y == null || !isFinite(y) || y < lo || y > hi) { pen = false; continue; }
            d += (pen ? ' L' : ' M') + SX(v).toFixed(1) + ',' + SY(y).toFixed(1);
            pen = true;
        }
        return d;
    }

    // 1. Идеальный газ проверяется одним числом: Z = pV/nRT должен быть тождественной единицей.
