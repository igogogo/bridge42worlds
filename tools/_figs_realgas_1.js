             '" stroke="' + LINK + '" stroke-width="2" stroke-dasharray="5,4"/>';
        s += txt(x1 - 54, SY(1) - 9, 'идеальный газ', LINK, 11);

        // измеренная кривая CO₂ при 20 °C: три подписанные точки — опорные
