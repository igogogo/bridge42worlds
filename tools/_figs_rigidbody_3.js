// 8. Шкала числа Россби: где Кориолис главный, а где его не видно.
F.rigirossby = function () {
    var W = 440, H = 200, x0 = 46, x1 = 400, y = 108;
    function X(lg) { return x0 + (lg + 2) * (x1 - x0) / 7; }
    var sup = ['&#8304;', '&#185;', '&#178;', '&#179;', '&#8308;', '&#8309;'];
    var s = txt(W / 2, 18, 'число Россби: инерция потока против Кориолиса', SOFT, 11);
    s += '<line x1="' + x0 + '" y1="' + y + '" x2="' + x1 + '" y2="' + y + '" stroke="' + INK + '" stroke-width="1.6"/>';
    [-2, -1, 0, 1, 2, 3, 4, 5].forEach(function (lg) {
        s += '<line x1="' + X(lg) + '" y1="' + (y - 5) + '" x2="' + X(lg) + '" y2="' + (y + 5) +
             '" stroke="' + SOFT + '" stroke-width="1"/>';
        s += txt(X(lg), y + 20, '10' + (lg < 0 ? '&#8315;' : '') + sup[Math.abs(lg)], SOFT, 10);
    });
    // граница Ro = 1
    s += '<line x1="' + X(0) + '" y1="' + (y - 46) + '" x2="' + X(0) + '" y2="' + (y + 8) +
         '" stroke="' + BORD + '" stroke-width="1.2" stroke-dasharray="4,3"/>';
    s += txt(X(0), y - 52, 'Ro = 1', SOFT, 10.5);
    function mark(lg, up, color, name, val) {
        var yy = up ? y - 22 : y + 44;
        var o = mol(X(lg), y, 6, color);
        o += '<line x1="' + X(lg) + '" y1="' + y + '" x2="' + X(lg) + '" y2="' + (up ? yy + 6 : yy - 12) +
             '" stroke="' + color + '" stroke-width="1.2"/>';
        o += txt(X(lg), yy, name, color, 11.5);
        o += txt(X(lg), up ? yy - 14 : yy + 14, val, SOFT, 10);
        return o;
    }
    s += mark(Math.log(0.097) / Math.LN10, true, LINK, 'циклон', '0,097');
    s += mark(Math.log(163) / Math.LN10, false, INK, 'снаряд', '1,6&#183;10&#178;');
    s += mark(Math.log(14550) / Math.LN10, true, WARN, 'раковина', '1,5&#183;10&#8308;');
    s += txt(x0, 192, 'Кориолис правит движением', LINK, 10.5, 'start');
    s += txt(x1, 192, 'Кориолиса не видно', WARN, 10.5, 'end');
    return svg(W, H, s);
};

