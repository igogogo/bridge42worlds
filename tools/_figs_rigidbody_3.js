    s += arrow(ax, ay, ax + 96, ay, LINK, 'ahl');
    s += txt(ax + 104, ay + 4, 'v', LINK, 13, 'start');
    s += arrow(ax, ay, ax + 92, ay - 30, WARN, 'ahw');
