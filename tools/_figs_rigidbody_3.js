// 4. Лемма применяется дважды: к r и к v; собираются три слагаемых.
F.rigitwice = function () {
    var W = 430, H = 220;
    var s = txt(W / 2, 18, 'одна и та же лемма — два раза подряд', SOFT, 11);
    function box(x, y, w, h, c, t1, t2) {
        var o = '<rect x="' + x + '" y="' + y + '" width="' + w + '" height="' + h + '" rx="7" fill="none" stroke="' +
                c + '" stroke-width="1.5"/>';
        o += txt(x + w / 2, y + 22, t1, c, 12.5);
        if (t2) o += txt(x + w / 2, y + 38, t2, SOFT, 10.5);
        return o;
    }
    s += box(24, 36, 150, 50, SOFT, 'r', 'радиус-вектор');
    s += arrow(180, 61, 244, 61, INK);
    s += txt(212, 52, 'лемма', SOFT, 10);
    s += box(250, 36, 156, 50, LINK, 'v = v&#8242; + &#969;&#215;r', 'первый раз');
    s += arrow(328, 92, 328, 118, INK);
    s += txt(340, 108, 'лемма ещё раз', SOFT, 10, 'start');
    s += box(24, 124, 382, 62, WARN,
             'a = a&#8242; + 2&#183;&#969;&#215;v&#8242; + &#969;&#215;(&#969;&#215;r)',
             'относительное + кориолисово + центробежное');
    s += txt(W / 2, 212, 'два одинаковых слагаемых и дают двойку', SOFT, 11);
    return svg(W, H, s);
};

// 5. Откуда двойка: два механизма, каждый даёт ω·v·dt.
