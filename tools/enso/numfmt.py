"""Одно округление на всех.

Одна и та же величина лежит в нескольких файлах и печатается на нескольких сценах. Если её
округляют разные руки, на панели появляются два числа: python `round(2.715, 2)` даёт 2.71 (в
двоичной записи это 2.71499…), `f"{2.715:.2f}"` тоже 2.71, а панель через `Math.round` покажет
2.72. Так «кто выбивается» и карточка состояния разошлись на 17.09.

Здесь ровно одно правило, то же, что у панели: половина уходит вверх, и решает десятичная
запись числа, а не его двоичный хвост. Всё, что пишет число для показа или для сравнения
с показанным, идёт сюда.
"""
from decimal import Decimal, ROUND_HALF_UP


def r2(x, nd=2):
    """Округление по десятичной записи, половина вверх (как Math.round для положительных).
    None остаётся None; сюда же можно давать строку или numpy-число."""
    if x is None:
        return None
    q = Decimal(1).scaleb(-nd)
    return float(Decimal(repr(float(x))).quantize(q, rounding=ROUND_HALF_UP))
