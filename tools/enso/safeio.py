# -*- coding: utf-8 -*-
"""Запись файла, которая переживает осечку файловой системы и не оставляет половину файла.

ЗАЧЕМ. С 15 по 17 сентября запись json на этой машине сорвалась четырежды на совершенно
исправном коде: `OSError: [Errno 22] Invalid argument` на ОТКРЫТИИ файла, который лежит
на месте и прекрасно открывается через секунду. Дважды это уронило шаг облаков понятий в
выкладке, один раз phase.py, один раз planet.py — и тогда раздел истории измерений просто
не обновился за сутки, а в логе осталась трассировка, которую надо читать глазами.
Затыкать это повтором в каждом скрипте по отдельности — значит через месяц иметь четыре
разных повтора и один пропущенный.

ДВА СВОЙСТВА СРАЗУ, И ВТОРОЕ ВАЖНЕЕ ПЕРВОГО:

  · ПОВТОР. Осечка разовая: со второго раза проходит. Пробуем четыре раза с нарастающей
    паузой и говорим об этом вслух — молчаливый повтор прячет болезнь, а она может
    оказаться не разовой.

  · ЗАМЕНА ЦЕЛИКОМ. Пишем во временный файл РЯДОМ с целью и подменяем им цель одним
    движением: os.replace в пределах одного тома атомарен. Читатель — панель в браузере,
    выкладка, соседний скрипт — видит либо старый файл, либо новый, но никогда половину
    нового. Прежняя запись поверх цели оставляла именно половину, если срывалась на
    середине: json.dumps уже отдал строку, а запись не дошла до конца.

ПЕРЕВОДЫ СТРОК НЕ МЕНЯЮТСЯ. Открываем как это делал Path.write_text — без указания newline,
то есть с обычным переводом \\n в \\r\\n на Windows. Иначе половина файлов данных сменила бы
окончания строк, и git показал бы, что изменилось всё.
"""
import os
import time
from pathlib import Path

TRIES = 4


def write_text(path, text, encoding="utf-8", tries=TRIES, quiet=False):
    """Заменить файл текстом целиком. Возвращает Path. Бросает последнюю ошибку, если не вышло."""
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_name(p.name + ".tmp%d" % os.getpid())
    last = None
    for i in range(max(1, tries)):
        try:
            with open(tmp, "w", encoding=encoding) as f:
                f.write(text)
            os.replace(tmp, p)
            return p
        except OSError as e:                                     # noqa: PERF203
            last = e
            try:
                os.unlink(tmp)
            except OSError:
                pass
            if i + 1 < tries:
                if not quiet:
                    print("  запись %s сорвалась (errno %s), повтор %d" % (p.name, e.errno, i + 1))
                time.sleep(0.4 * (i + 1))
    raise last


def write_json(path, obj, tries=TRIES, **dumps_kw):
    """То же самое, но сериализует само. ensure_ascii=False по умолчанию — как везде у нас."""
    import json
    dumps_kw.setdefault("ensure_ascii", False)
    return write_text(path, json.dumps(obj, **dumps_kw), tries=tries)
