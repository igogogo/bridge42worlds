# Свободный ответ по всему курсу засчитывается по двум совпавшим ключевым словам,
# а у этих шести тем поле не стояло вовсе — засчитывалось одно.
NEEDED_FOR_FREE = 2


def main():
    hints = fixed = 0
    for lesson, table in HINTS.items():
        topic, lid = lesson.split("/")
        f = ROOT / topic / (lid + ".json")
        d = json.loads(f.read_text(encoding="utf-8"))
        ru = d["ru"]
        for q in ru.get("quiz", []):
            if q["id"] in table and not q.get("hint"):
                q["hint"] = table[q["id"]]
                hints += 1
            if q.get("type") == "free" and not q.get("needed"):
                q["needed"] = NEEDED_FOR_FREE
                fixed += 1
        # тот же текст кладём в остальные языки как заготовку: конвейер переводит по кириллице
        for lang in ("en", "es", "ar", "fr"):
            br = d.get(lang)
            if not br or not br.get("quiz"):
                continue
            by_id = {q["id"]: q for q in ru["quiz"]}
            for q in br["quiz"]:
                src = by_id.get(q["id"])
                if not src:
                    continue
                if src.get("hint") and not q.get("hint"):
                    q["hint"] = src["hint"]
                if src.get("needed") and not q.get("needed"):
                    q["needed"] = src["needed"]
        f.write_text(json.dumps(d, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print("подсказок написано: %d | свободных вопросов с порогом: %d" % (hints, fixed))
    print("остальные языки: заготовки по-русски, переводит course_translate.py --fill")


if __name__ == "__main__":
    main()
