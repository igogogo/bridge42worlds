// Шаг 2. Складываем энергию по точкам — сумма Σm r² выносится сама
// ─────────────────────────────────────────────────────────────────────────────
F.rigisum = function () {
    var W = 440, H = 215, cx = 112, cy = 106;
    var s = '<circle cx="' + cx + '" cy="' + cy + '" r="74" fill="' + LINK + '" opacity="0.06" stroke="' + BORD + '"/>';
    var pts = [[-52, -28], [-18, 44], [28, -50], [56, 20], [8, 6], [-40, 24], [42, -14]];
    for (var i = 0; i < pts.length; i++) {
        var x = cx + pts[i][0], y = cy + pts[i][1];
        s += '<line x1="' + cx + '" y1="' + cy + '" x2="' + x + '" y2="' + y + '" stroke="' + SOFT +
             '" stroke-width="0.8" stroke-dasharray="2,3"/>';
        s += mol(x, y, 5, i === 2 ? WARN : LINK);
    }
    s += mol(cx, cy, 4, INK);
    s += txt(cx + 44, cy - 60, 'm&#7522;, r&#7522;', WARN, 11, 'start');
    s += txt(cx, cy + 100, 'каждая точка вносит своё', SOFT, 11);
    // выкладка справа
    var xr = 236;
    s += txt(xr, 62, 'E = &#931; &#189;m&#7522;(&#969;r&#7522;)&#178;', INK, 14, 'start');
    s += txt(xr, 100, 'E = &#189; (&#931; m&#7522;r&#7522;&#178;) &#969;&#178;', INK, 14, 'start');
    s += '<line x1="' + (xr + 44) + '" y1="107" x2="' + (xr + 116) + '" y2="107" stroke="' + WARN + '" stroke-width="1.5"/>';
    s += arrow(xr + 80, 112, xr + 80, 136, WARN, 'ahw');
    s += txt(xr + 80, 154, 'это и есть I', WARN, 13);
    s += txt(xr + 80, 174, 'кг &#183; м&#178;', SOFT, 11);
    s += txt(xr, 202, '&#969; одна на всё тело — потому и выносится', SOFT, 11, 'start');
    return svg(W, H, s);
};

