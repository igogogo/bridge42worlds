// ─────────────────────────────────────────────────────────────────────────────
// Шаг 8. Гонка с горки: обруч приходит последним
// ─────────────────────────────────────────────────────────────────────────────
F.rigiroll = function () {
    var W = 460, H = 225, x0 = 40, y0 = 40, x1 = 400, y1 = 156;
    var s = '<line x1="' + x0 + '" y1="' + y0 + '" x2="' + x1 + '" y2="' + y1 + '" stroke="' + INK + '" stroke-width="2.5"/>';
    s += '<line x1="' + x0 + '" y1="' + y1 + '" x2="' + (x1 + 26) + '" y2="' + y1 + '" stroke="' + SOFT + '" stroke-width="1.5"/>';
    s += '<line x1="' + x0 + '" y1="' + y0 + '" x2="' + x0 + '" y2="' + y1 + '" stroke="' + SOFT +
         '" stroke-width="1" stroke-dasharray="3,3"/>';
    s += txt(x0 - 16, (y0 + y1) / 2, 'h', SOFT, 14);
    // нормаль к склону, чтобы тела лежали НА доске, а не пересекали её
    var dx = y1 - y0, dy = -(x1 - x0), len = Math.sqrt(dx * dx + dy * dy);
    var race = [[0.50, 'обруч', WARN, true], [0.68, 'диск', LINK, false], [0.83, 'шар', LINK, false]];
    for (var i = 0; i < race.length; i++) {
        var f = race[i][0], r = 13;
        var bx = x0 + (x1 - x0) * f + dx / len * r, by = y0 + (y1 - y0) * f + dy / len * r;
        var col = race[i][2];
        if (race[i][3]) s += '<circle cx="' + bx + '" cy="' + by + '" r="' + r + '" fill="none" stroke="' + col + '" stroke-width="5"/>';
        else s += '<circle cx="' + bx + '" cy="' + by + '" r="' + r + '" fill="' + col + '" opacity="0.30" stroke="' + col + '"/>';
        s += txt(bx, by - r - 8, race[i][1], col, 11);
    }
    s += txt(x1 + 14, y1 + 18, 'финиш', SOFT, 11);
    s += txt(150, 190, 'v = &#8730;( 2gh / (1+k) )', INK, 17);
    s += txt(150, 212, 'ни массы, ни радиуса в ответе нет', SOFT, 11);
    s += txt(352, 190, 'k = 1 &#183; &#189; &#183; &#8534;', SOFT, 11);
    s += txt(352, 210, '3,13 &#183; 3,62 &#183; 3,74 м/с', WARN, 11);
    return svg(W, H, s);
};

