// Шаг 3. Момент силы: крутит только касательная составляющая
// ─────────────────────────────────────────────────────────────────────────────
F.rigitorque = function () {
    var W = 440, H = 220, cx = 148, cy = 118, R = 80;
    var s = '<circle cx="' + cx + '" cy="' + cy + '" r="' + R + '" fill="none" stroke="' + BORD + '" stroke-width="1.5"/>';
    s += mol(cx, cy, 5, INK);
    s += txt(cx - 18, cy + 18, 'ось', SOFT, 11);
    // точка приложения силы — под 45° вверх-вправо
    var px = Math.round(cx + R * 0.7071), py = Math.round(cy - R * 0.7071);
    s += '<line x1="' + cx + '" y1="' + cy + '" x2="' + px + '" y2="' + py + '" stroke="' + SOFT +
         '" stroke-width="1" stroke-dasharray="3,3"/>';
    s += txt(cx + 30, cy - 22, 'r', SOFT, 13);
    s += mol(px, py, 6, INK);
    // разложение: радиальная (21,-21) + касательная (39,39) = полная (60,18)
    var rd = [21, -21], tg = [39, 39], fu = [60, 18];
    s += arrow(px, py, px + rd[0], py + rd[1], SOFT);
    s += txt(px + 30, py - 26, 'F&#7523; — не крутит', SOFT, 11, 'start');
    s += arrow(px, py, px + tg[0], py + tg[1], LINK, 'ahl');
    s += txt(px + 46, py + 56, 'F&#8348; — только она крутит', LINK, 11, 'start');
    s += arrow(px, py, px + fu[0], py + fu[1], WARN, 'ahw');
    s += txt(px + 68, py + 14, 'F', WARN, 15, 'start');
    // пунктиры параллелограмма
    s += '<path d="M' + (px + rd[0]) + ',' + (py + rd[1]) + ' L' + (px + fu[0]) + ',' + (py + fu[1]) +
         ' M' + (px + tg[0]) + ',' + (py + tg[1]) + ' L' + (px + fu[0]) + ',' + (py + fu[1]) +
         '" fill="none" stroke="' + BORD + '" stroke-width="1" stroke-dasharray="3,3"/>';
    // дуга поворота на dφ
    s += '<path d="M' + (cx + R + 8) + ',' + cy + ' a ' + (R + 8) + ',' + (R + 8) + ' 0 0 1 -16,28" fill="none" stroke="' +
         INK + '" stroke-width="1.6" marker-end="url(#ah)"/>';
    s += txt(cx + R + 26, cy + 34, 'd&#966;', INK, 12);
    // правая колонка
    s += txt(362, 108, 'dA = F&#8348; &#183; r &#183; d&#966;', INK, 14);
    s += txt(362, 142, 'M = F&#8348; &#183; r', INK, 18);
    s += txt(362, 166, 'сила на плечо', SOFT, 11);
    s += txt(362, 186, 'Н &#183; м', SOFT, 11);
    return svg(W, H, s);
};

