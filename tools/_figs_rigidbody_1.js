// ─────────────────────────────────────────────────────────────────────────────
// Шаг 6. Коэффициенты формы: обруч 1, диск ½, шар ⅖, стержень 1/12
// ─────────────────────────────────────────────────────────────────────────────
F.rigishapes = function () {
    var W = 460, H = 200, y = 80, rr = 30;
    var xs = [66, 178, 290, 402];
    var s = txt(230, 26, 'k = &#10216;r&#178;&#10217; / R&#178;  —  средний квадрат расстояния до оси', INK, 13);
    // обруч — только обод
    s += '<circle cx="' + xs[0] + '" cy="' + y + '" r="' + rr + '" fill="none" stroke="' + LINK + '" stroke-width="7"/>';
    // диск — равномерная заливка
    s += '<circle cx="' + xs[1] + '" cy="' + y + '" r="' + rr + '" fill="' + LINK + '" opacity="0.35" stroke="' + LINK + '"/>';
    // шар — заливка РОВНО такая же, как у диска: шар однородный, гуще к центру он не становится
    // (иначе k был бы меньше ⅖ — ровно этим и отличается Земля с её 0,3307 в блоке констант).
    // Объём подсказывает не плотность, а экватор-эллипс.
    s += '<circle cx="' + xs[2] + '" cy="' + y + '" r="' + rr + '" fill="' + LINK + '" opacity="0.35" stroke="' + LINK + '"/>';
    s += '<ellipse cx="' + xs[2] + '" cy="' + y + '" rx="' + rr + '" ry="' + (rr * 0.34) + '" fill="none" stroke="' +
         LINK + '" stroke-width="1" stroke-dasharray="3,3"/>';
    // стержень — тонкая полоса поперёк оси; ВСЯ его длина равна R остальных тел,
    // потому что k = 1/12 записан именно к длине: I = mL²/12
    s += '<rect x="' + (xs[3] - rr / 2) + '" y="' + (y - 6) + '" width="' + rr + '" height="12" fill="' + LINK +
         '" opacity="0.35" stroke="' + LINK + '"/>';
    var names = ['обруч', 'диск', 'шар', 'стержень'];
    var ks = ['k = 1', 'k = &#189;', 'k = &#8534;', 'k = 1/12'];
    var notes = ['вся масса на R', 'размазана ровно', 'у полюсов ближе к оси', 'R — это вся длина'];
    for (var i = 0; i < 4; i++) {
        s += mol(xs[i], y, 3.5, INK);
        s += txt(xs[i], y + rr + 22, names[i], INK, 12);
        s += txt(xs[i], y + rr + 42, ks[i], WARN, 14);
        s += txt(xs[i], y + rr + 60, notes[i], SOFT, 10);
    }
    return svg(W, H, s);
};

