/* _figs_rigidbody_1.js — ЗАГОТОВКА схем для параграфа rigidbody/01-inertia.
   Восемь функций, по одной на каждый шаг вывода. Ведущая сессия вклеивает их
   в js/figures.js как есть — js/figures.js я не трогаю.

   Из окружения figures.js используются готовые вещи, своих я не завожу:
     svg(w, h, body)                       — обёртка <svg> с маркерами ah / ahl / ahw
     txt(x, y, s, color, size, anchor)     — текст; s проходит через label() → перевод
     arrow(x1, y1, x2, y2, color, marker)  — линия со стрелкой
     mol(cx, cy, r, fill)                  — кружок
     цвета: INK, SOFT, LINK, WARN, BORD, MOSS

   Маркеры стрелок есть только трёх цветов (ah — INK, ahl — LINK, ahw — WARN),
   поэтому цвета стрелок здесь этими тремя и ограничены; MOSS идёт только на заливки.
   Греческие буквы и индексы — сущностями, чтобы не зависеть от кодировки страницы.
   Русские словесные подписи выписаны списком в самом конце файла — их переводить.

   ── общий словарь сущностей, чтобы не искать по коду ──
   &#969; ω   &#949; ε   &#966; φ   &#931; Σ   &#945; α   &#8730; √
   &#178; ²   &#183; ·   &#8594; →   &#215; ×
   &#8321; ₁  &#8322; ₂  &#7522; ᵢ  &#7580; ᶜ  &#189; ½   &#8534; ⅖
   &#8348; ₜ  &#7523; ᵣ  &#10216; ⟨  &#10217; ⟩
*/

