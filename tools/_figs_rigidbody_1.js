// Шаг 1. Одна ω на всё тело, у каждой точки своя v = ω·r
// ─────────────────────────────────────────────────────────────────────────────
F.rigiomega = function () {
    var W = 440, H = 240, cx = 145, cy = 105, R = 74, r1 = 30, r2 = 66;
    var s = '<circle cx="' + cx + '" cy="' + cy + '" r="' + R + '" fill="' + LINK + '" opacity="0.07" stroke="' + BORD + '"/>';
    // спица, на которой сидят обе точки
    s += '<line x1="' + cx + '" y1="' + cy + '" x2="' + (cx + R) + '" y2="' + cy + '" stroke="' + SOFT +
         '" stroke-width="1" stroke-dasharray="3,3"/>';
    s += mol(cx, cy, 5, INK);
    s += txt(cx - 16, cy + 18, 'ось', SOFT, 11);
    // дуга ω над диском
    s += '<path d="M' + (cx + 8) + ',' + (cy - R - 10) + ' a 46,46 0 0 1 44,16" fill="none" stroke="' + INK +
         '" stroke-width="1.6" marker-end="url(#ah)"/>';
    s += txt(cx + 26, cy - R - 18, '&#969;', INK, 15);
    // две точки на разных радиусах — скорости пропорциональны r
    s += mol(cx + r1, cy, 6, LINK);
    s += mol(cx + r2, cy, 6, WARN);
    s += arrow(cx + r1, cy, cx + r1, cy - 26, LINK, 'ahl');
    s += arrow(cx + r2, cy, cx + r2, cy - 57, WARN, 'ahw');
    s += txt(cx + r1 - 15, cy - 30, 'v&#8321;', LINK, 12);
    s += txt(cx + r2 + 15, cy - 61, 'v&#8322;', WARN, 12);
    // размеры r1, r2 — под диском, чтобы не лезть на заливку
    var yd1 = 196, yd2 = 220;
    [[cx, yd2], [cx + r1, yd1], [cx + r2, yd2]].forEach(function (p) {
        s += '<line x1="' + p[0] + '" y1="' + (cy + 8) + '" x2="' + p[0] + '" y2="' + p[1] +
             '" stroke="' + BORD + '" stroke-width="1" stroke-dasharray="2,3"/>';
    });
    s += arrow(cx, yd1, cx + r1, yd1, SOFT);
    s += txt(cx + r1 / 2, yd1 - 6, 'r&#8321;', SOFT, 11);
    s += arrow(cx, yd2, cx + r2, yd2, SOFT);
    s += txt(cx + r2 / 2, yd2 - 6, 'r&#8322;', SOFT, 11);
    // правая колонка
    s += txt(345, 66, 'угол поворота', SOFT, 11);
    s += txt(345, 82, 'у всех точек один', SOFT, 11);
    s += txt(345, 116, 'v&#7522; = &#969; &#183; r&#7522;', INK, 18);
    s += txt(345, 140, 'а скорость — своя', SOFT, 11);
    s += txt(345, 176, 'r — расстояние до ОСИ,', WARN, 11);
    s += txt(345, 192, 'не до центра тела', WARN, 11);
    return svg(W, H, s);
};

