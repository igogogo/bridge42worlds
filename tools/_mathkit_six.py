def main():
    d = json.load(io.open(P, encoding="utf-8"))
    ru = d["ru"]["items"]
    order = d["items"]
    have = {x["id"] for x in order}
    added = []
    for key, card in CARDS.items():
        if key in have:
            continue
        ru[key] = {k: card[k] for k in ("name", "means", "where", "catch", "latex")}
        order.append({"id": key, "level": card["level"], "icon": card["icon"], "latex": card["latex"]})
        added.append(key)
    # порядок карточек — по уровням, как и был: основа → изменение → направление → язык
    rank = {"base": 0, "calc": 1, "vector": 2, "adv": 3}
    order.sort(key=lambda x: rank.get(x.get("level"), 9))
    io.open(P, "w", encoding="utf-8").write(json.dumps(d, ensure_ascii=False, indent=1) + "\n")
    print("карточек в справочнике: %d | добавлено: %d (%s)" % (len(order), len(added), ", ".join(added)))


if __name__ == "__main__":
    main()
