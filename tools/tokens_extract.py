# -*- coding: utf-8 -*-
"""Собирает css/tokens.css из css/style.css — один источник цветов и сетки.

ЗАЧЕМ. Часть страниц сделана самодостаточными: сообщество, «как подготовить работу»,
гид. У каждой свой <style>, и общий style.css они намеренно НЕ подключают — чтобы
правка компонента (карточки, ленты) не могла их сломать. Мысль здравая, но вместе с
компонентами каждая страница унесла к себе и ПАЛИТРУ, а копии разъехались:

    community-prepare  охра #B5651D, циан #2E9E8F   (в бренде #C77F3A / #2E8AA0)
    about / community  тёмный фон #0B111E            (на сайте #1b1f27)
    about              serif без Source Serif 4      (у соседа с ним)
    ширины 680 / 720 / 760                           (на сайте 748)

То есть ровно то, чего владелец просил не допускать: «не заводить вторую палитру».

КАК ЛЕЧИМ. Токены — это не компоненты: объявление переменной ничего не может сломать,
оно только даёт значение. Поэтому самодостаточность страниц сохраняем (компонентных
правил они по-прежнему ниоткуда не берут), а палитру и сетку выносим в отдельный
файл — и выводим его ИЗ style.css, а не пишем руками. Написанный руками файл стал бы
четвёртой копией и разъехался бы так же.

ТЕМА. Главные страницы темнеют по сохранённому выбору (data-theme, js/search.js),
самодостаточные — по системной настройке. Здесь это расхождение НЕ трогаем: задача
прохода — свести значения, а не менять поведение. Поэтому tokens.css отдаёт тёмные
значения под обоими селекторами, и каждая страница продолжает темнеть так, как умела.
"""
import io, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "css" / "style.css"
DST = ROOT / "css" / "tokens.css"
NL = chr(10)


def block(css, opener, after=0):
    """Тело правила от opener до парной закрывающей скобки."""
    i = css.index(opener, after)
    j = css.index("{", i) + 1
    depth = 1
    k = j
    while depth:
        ch = css[k]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        k += 1
    return css[j:k - 1].strip(NL), k


def build():
    css = io.open(SRC, encoding="utf-8", newline="").read().replace(chr(13) + chr(10), NL)
    brand = css.index("брендовая дизайн-система")
    light, _ = block(css, ":root", brand)
    dark, _ = block(css, 'html[data-theme="dark"]')
    # Ширины объявлены отдельным :root ниже по файлу (правка «одна сетка на весь
    # сайт» дописывалась в конец, чтобы перебить старые значения). Забираем и её —
    # без неё в tokens.css нет самого главного: --w-text.
    widths, _ = block(css, ":root", css.index("--w-text:") - 600)
    light = light + NL + widths

    # Шкала касания — тоже сетка, только для пальца. У самодостаточных страниц она
    # была скопирована руками, с припиской «правишь там — правь и здесь, иначе
    # раздел молча уедет». Ровно от этой приписки и избавляемся.
    tap, _ = block(css, ":root", css.index("--tap-lg:") - 400)
    light = light + NL + tap
    tap_mob, _ = block(css, ":root", css.index("--tap-lg: 48px") - 300)

    # выкидываем то, что относится к компонентам, а не к теме: фоновая картинка-иконка
    light = NL.join(l for l in light.split(NL) if "--ic-lamp" not in l)

    out = (
        "/* ═══ tokens.css — палитра и сетка bridge42worlds ═══" + NL +
        "   СОБРАН АВТОМАТИЧЕСКИ из css/style.css (tools/tokens_extract.py)." + NL +
        "   Руками не править: правка уедет при следующей сборке. Источник — style.css." + NL + NL +
        "   Файл нужен страницам, которые намеренно не подключают общий style.css" + NL +
        "   (сообщество, подготовка работы, гид): они держат свои компоненты, но цвета" + NL +
        "   и ширины берут отсюда, чтобы не разъезжаться с остальным сайтом. */" + NL + NL +
        ":root {" + NL + light + NL + "}" + NL + NL +
        "/* Тёмная тема по сохранённому выбору — как на главных страницах. */" + NL +
        'html[data-theme="dark"], :root[data-theme="dark"] {' + NL + dark + NL + "}" + NL + NL +
        "/* ...и по системной настройке — так темнеют самодостаточные страницы." + NL +
        "   Расхождение поведения оставлено как было; сведены значения, не механизм. */" + NL +
        "/* Палец вместо мыши — ступени крупнеют на узком экране. */" + NL +
        "@media (max-width: 640px) {" + NL + "  :root {" + NL + tap_mob + NL + "  }" + NL + "}" + NL + NL +
        "@media (prefers-color-scheme: dark) {" + NL +
        '  :root:not([data-theme="light"]) {' + NL + dark + NL + "  }" + NL +
        "}" + NL
    )
    io.open(DST, "w", encoding="utf-8", newline="").write(out)
    n = len(re.findall(r"--[a-z0-9-]+\s*:", out))
    print("css/tokens.css собран, объявлений:", n)


if __name__ == "__main__":
    build()
