import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
DATA = ROOT / "data"

if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace", line_buffering=True)


def delta_ratio(X, n_quads=200000, seed=42):
    """δ Громова, делённая на диаметр. Считается по случайным четвёркам.

    Полный перебор четвёрок — это n⁴, на двух тысячах точек уже 16 триллионов.
    Случайная выборка отвечает на тот же вопрос: δ определяется как максимум, но нас
    интересует не рекорд, а типичное поведение, поэтому печатаем и медиану, и верхний
    хвост. Рекорд по одной случайной четвёрке всё равно недостижим честно.
    """
    import numpy as np
    rng = np.random.default_rng(seed)
    n = len(X)
    q = rng.integers(0, n, size=(n_quads, 4))
    q = q[(q[:, 0] != q[:, 1]) & (q[:, 0] != q[:, 2]) & (q[:, 0] != q[:, 3]) &
          (q[:, 1] != q[:, 2]) & (q[:, 1] != q[:, 3]) & (q[:, 2] != q[:, 3])]
    a, b, c, d = (X[q[:, i]] for i in range(4))

    def dist(u, v):
        # Угловое расстояние на сфере: векторы единичные, и угол — честная метрика,
        # в отличие от хорды, которая на больших углах насыщается и врёт о дальних парах.
        return np.arccos(np.clip(np.sum(u * v, axis=1), -1, 1))

    s1 = dist(a, b) + dist(c, d)
    s2 = dist(a, c) + dist(b, d)
    s3 = dist(a, d) + dist(b, c)
    S = np.sort(np.stack([s1, s2, s3], axis=1), axis=1)
    delta = (S[:, 2] - S[:, 1]) / 2
    # Диаметр четвёрки — по ней же, а не по всему облаку: иначе редкая далёкая пара
    # задавит нормировку и все доли поедут вниз одинаково.
    diam = np.maximum(np.max(np.stack([dist(a, b), dist(a, c), dist(a, d),
                                       dist(b, c), dist(b, d), dist(c, d)], axis=1),
                             axis=1), 1e-9)
    return delta / diam


def load(what):
    import numpy as np
    if what == "ours":
        vecs = []
        with (DATA / "embeddings-articles.jsonl").open(encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    r = json.loads(line)
                    if r.get("vec"):
                        vecs.append(r["vec"])
        M = np.asarray(vecs, dtype=np.float32)
    else:
        import vecstore
        _, m = vecstore.load(DATA / "field", latest=True)
        M = np.asarray(m[::max(1, len(m) // 20000)], dtype=np.float32)
    M /= np.linalg.norm(M, axis=1, keepdims=True) + 1e-9
    return M


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--what", default="ours", choices=("ours", "field"))
    ap.add_argument("--quads", type=int, default=200000)
    args = ap.parse_args()
    import numpy as np

    M = load(args.what)
    print(f"{args.what}: {len(M):,} точек, {M.shape[1]} измерений")

    rng = np.random.default_rng(0)
    R = rng.standard_normal(M.shape).astype(np.float32)
    R /= np.linalg.norm(R, axis=1, keepdims=True)

    # Дерево как второй эталон: показывает, куда вообще смещается число, когда
    # структура ЕСТЬ. Без него непонятно, много ли «0,17» или мало.
    depth, branch = 8, 3
    pts = [np.zeros(M.shape[1], dtype=np.float32)]
    for _ in range(depth):
        new = []
        for p in pts[-branch ** 0:] if len(pts) < 3000 else []:
            pass
        cur = pts[-min(len(pts), 900):]
        for p in cur:
            for _ in range(branch):
                v = p + rng.standard_normal(M.shape[1]).astype(np.float32) * 0.5
                new.append(v)
        pts.extend(new[:2000])
    T = np.asarray(pts[:len(M)], dtype=np.float32)
    T /= np.linalg.norm(T, axis=1, keepdims=True) + 1e-9

    print(f"\n{'что':<26} {'медиана δ/диаметр':>18} {'верхние 5%':>12} {'максимум':>10}")
    for name, X in (("НАШИ ДАННЫЕ", M), ("случайное облако", R), ("настоящее дерево", T)):
        d = delta_ratio(X, args.quads)
        print(f"{name:<26} {np.median(d):>18.3f} {np.quantile(d, 0.95):>12.3f} "
              f"{d.max():>10.3f}")
    print("\nЧитать так: у дерева δ близка к нулю при любом размере, у бесструктурного")
    print("облака — заметно выше. Если наши данные ближе к дереву, чем к облаку,")
    print("гиперболическая геометрия им подходит лучше плоской, и это можно проверить")
    print("дообучением. Если они сидят рядом со случайным облаком — иерархии, которую")
    print("стоило бы ловить геометрией, в нашем корпусе нет, и вопрос закрыт числом.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
