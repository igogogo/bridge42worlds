# -*- coding: utf-8 -*-
"""Проверка выхода движка рекомендаций: четыре проверки из системной роли.

Источник требований — `задачи/РЕКОМЕНДАЦИИ-АВТОРАМ.md`, §1 «Проверка выхода».
Сказали лишнее ловят проверки 1–3, сказали слишком мало — проверка 4.

ГЛАВНОЕ АРХИТЕКТУРНОЕ РЕШЕНИЕ — ПОЧЕМУ coverage ВОЗВРАЩАЕТ ЧИСЛО, А НЕ СПИСОК.
Роль требует: перечень слабых мест живёт в памяти прогона и не записывается никуда —
ни в лог, ни в поле данных, ни в кэш. Если функция ВЕРНЁТ этот список наружу, требование
переедет на совесть вызывающего: достаточно один раз положить ответ в переменную,
которая попадёт в отладочный вывод, — и покрытие куплено ценой досье.

Поэтому список существует только внутри `coverage()`, в локальной области, и наружу
уходит одно число: сколько существенных мест осталось без намёка. Дописать намёк
вызывающий может, перезапустив генерацию с требованием «шире», — не зная, о чём речь.
Это неудобно намеренно: неудобство здесь дешевле утечки.

ПОРЯДОК ВЫЗОВА. Проверять НАДО ДО записи файла. Если сначала сохранить черновик,
а потом проверить, то черновик с критикой уже коснулся диска — требование нарушится
самим порядком операций, а не текстом.

    from output_guard import check_all
    verdict = check_all(article_text, draft)   # draft НИКУДА не сохранён
    if verdict["ok"]: save(draft)
"""
import json, re, time
import urllib.request, urllib.error

# --- проверка 1: стоп-слова и стоп-обороты (таблицы роли, §1) ---
# Слова из таблицы роли делятся на два вида, и это не придирка, а замер:
# самопроверка на образце, который должен быть ЧИСТЫМ, поймала «слаб» в словах
# «измеряет СЛАБые поля» — предмет исследования, а не оценка работы. Тот же класс
# ошибки, что `imu`, совпавшее в «maximum» (blindspot_filter.py).
#
# Поэтому: безусловные слова снимают абзац всегда — вне оценки работы они не встречаются.
# Двусмысленные — обычные термины («слабое поле», «ошибка измерения», «ограничение
# сверху»), и засчитываются ТОЛЬКО когда в том же предложении речь о самой работе.
STOP_ALWAYS = ["неубедительн", "устарел", "тривиальн", "следовало бы",
               "автору стоило", "к сожалению", "всего лишь"]
# «ПОВЕРХНОСТНЫЙ» — ДВА РАЗНЫХ СЛОВА. Как оценка работы это запрещённое слово: мы не
# критикуем автора. Но в океанографии это основной термин — поверхностная температура,
# поверхностный слой, поверхностные течения; на теме Эль-Ниньо он в каждой второй работе.
# 4 сентября из-за этого потерялись рекомендации у одиннадцати разобранных работ: страж
# резал их за фразу «поверхностная температура океана». Теперь слово запрещено только
# тогда, когда за ним НЕ стоит физика.
# «ПОВЕРХНОСТНЫЙ» ЗАПРЕЩЁН ТОЛЬКО ПРО РАБОТУ. Перечислять физические сочетания оказалось
# бесполезно: их бесконечно много («поверхностным нагревом», «поверхностные проявления»,
# «поверхностных характеристик»). Правило проще и точнее по смыслу: это оценка, только когда
# слово стоит рядом с САМОЙ РАБОТОЙ — анализ, подход, вывод, статья. Во всех прочих случаях
# это океанография, и трогать её нельзя.
STOP_AMBIG = ["слаб", "недостат", "ошибк", "ограничени", "необходимо", "однако"]
WORK_WORDS = ["работ", "стать", "автор", "исследован", "вывод", "результат",
              "подход", "анализ", "методик"]
STOP_TURNS = [
    (r"если у вас", "допущение, что может быть и не так"),
    (r"что изменится,? если", "приглашение оправдываться"),
    (r"насколько .{0,30}чувствителен", "вопрос об упущении"),
    (r"сейчас это заметит", "суждение о ясности текста"),
    (r"не хватает|отсутству|не приведён|не приведен", "прямое указание на пробел"),
]


# Скомпилированные наборы: безусловные слова, двусмысленные, слова о работе и обороты.
# (Восстановлены 4 сентября: правка про «поверхностный» затёрла их вместе с блоком.)
_ALWAYS = re.compile("|".join(STOP_ALWAYS), re.I)
_AMBIG = re.compile("|".join(STOP_AMBIG), re.I)
_WORK = re.compile("|".join(WORK_WORDS), re.I)
_TURNS = [(re.compile(pp, re.I), why) for pp, why in STOP_TURNS]
_SURFACE = re.compile(r"поверхностн\w*", re.I)
_WORK_NEAR = re.compile("|".join(["работ", "стать", "автор", "исследован", "вывод",
                                  "подход", "анализ", "методик", "обзор", "изложен"]), re.I)


def _surface_hits(text):
    """Оценка работы — только когда слово стоит ВПЛОТНУЮ к самой работе.

    Окно в сорок символов ловило «Работа опирается на поверхностную температуру океана»:
    слово «работа» было в том же предложении, но относилось не к нему. Считаем по словам:
    два слова слева и два справа. «Анализ поверхностный» — оценка; «поверхностная
    температура океана» — океанография.
    """
    out = []
    toks = re.findall(r"\w+", text or "", re.U)
    low = [t.lower() for t in toks]
    for k, t in enumerate(low):
        if not t.startswith("поверхностн"):
            continue
        near = low[max(0, k - 2):k] + low[k + 1:k + 3]
        if not any(_WORK_NEAR.match(w) for w in near):
            continue
        out.append({"kind": "оценка работы", "found": toks[k],
                    "why": "оценка глубины самой работы; о работе мы не судим"})
    return out


def stop_hits(text):
    hits = []
    for m in _ALWAYS.finditer(text or ""):
        hits.append({"kind": "слово", "found": m.group(0)})
    hits += _surface_hits(text)
    # двусмысленные — по предложениям: слово засчитывается, только если в этом же
    # предложении говорится о работе, а не о предмете исследования
    for sent in re.split(r"(?<=[.!?])\s+", text or ""):
        if not _WORK.search(sent):
            continue
        for m in _AMBIG.finditer(sent):
            hits.append({"kind": "слово о работе", "found": m.group(0)})
    for rx, why in _TURNS:
        m = rx.search(text or "")
        if m:
            hits.append({"kind": "оборот", "found": m.group(0), "why": why})
    return hits


# --- проверка 2: вопросительный знак в абзацах о работе (правило 9) ---
def question_hits(paragraphs):
    return [i for i, p in enumerate(paragraphs) if "?" in p]


def paras(text):
    return [p.strip() for p in re.split(r"\n\s*\n", text or "") if p.strip()]


def _ds(prompt, key, model="deepseek-v4-flash", tries=3):
    body = json.dumps({
        "model": model, "temperature": 0.0, "max_tokens": 400,
        "thinking": {"type": "disabled"},   # иначе лимит уходит в размышления, ответ пуст
        "messages": [{"role": "user", "content": prompt}],
    }).encode("utf-8")
    for a in range(tries):
        try:
            req = urllib.request.Request(
                "https://api.deepseek.com/chat/completions", data=body,
                headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"})
            with urllib.request.urlopen(req, timeout=90) as r:
                d = json.loads(r.read().decode("utf-8"))
            return d["choices"][0]["message"]["content"].strip()
        except Exception:
            if a == tries - 1:
                raise
            time.sleep(2 ** a * 2)


FLAWLESS = (
    "Ниже абзац из рекомендаций автору научной работы.\n"
    "Вопрос ровно один: останется ли этот абзац осмысленным и полезным, если в работе "
    "НЕТ НИКАКИХ изъянов?\n"
    "«Контрольная серия без X сделала бы вывод неуязвимым» — останется, это следующий шаг.\n"
    "«А где контроль?» — не останется, это имеет смысл только при изъяне.\n"
    "Ответь одним словом: да или нет.\n\nАбзац:\n{p}"
)


def flawless_hits(paragraphs, key):
    """Проверка 3: абзацы, осмысленные только при наличии изъяна."""
    bad = []
    for i, p in enumerate(paragraphs):
        ans = (_ds(FLAWLESS.format(p=p[:1500]), key) or "").lower()
        if ans.startswith("нет"):
            bad.append(i)
    return bad


COVER = (
    "Ты читаешь научную работу и готовый разбор для её автора.\n"
    "Перечисли ДЛЯ СЕБЯ существенные слабые места работы, затем сверь: на каждое ли "
    "в разборе есть совет по усилению (совет, а не упрёк и не вопрос).\n"
    "Ответь ТОЛЬКО числом — сколько существенных мест осталось БЕЗ совета. "
    "Ничего кроме числа не пиши: перечень нужен тебе, а не мне.\n\n"
    "РАБОТА:\n{src}\n\nРАЗБОР:\n{out}"
)


def coverage(article_text, draft, key):
    """Проверка 4. Возвращает ЧИСЛО непокрытых мест, никогда — их список.

    Перечень существует внутри модели и внутри этой функции. Наружу он не уходит
    ни возвратом, ни исключением, ни печатью — см. шапку модуля о том, почему.
    """
    ans = _ds(COVER.format(src=(article_text or "")[:6000], out=(draft or "")[:6000]), key)
    m = re.search(r"\d+", ans or "")
    return int(m.group(0)) if m else 0


def check_all(article_text, draft, key=None):
    """Полная проверка ДО записи на диск. draft остаётся в памяти вызывающего."""
    ps = paras(draft)
    res = {
        "stop": stop_hits(draft),
        "questions": question_hits(ps),
        "flawless_bad": [],
        "uncovered": 0,
        "paragraphs": len(ps),
    }
    if key:
        res["flawless_bad"] = flawless_hits(ps, key)
        res["uncovered"] = coverage(article_text, draft, key)
    # Блокируют только ТОЧНЫЕ признаки. Двусмысленные слова идут предупреждением.
    #
    # Почему так, замер 2026-08-05: рекомендованная самой ролью фраза «Эта работа
    # пригодится тем, кто измеряет СЛАБые поля» содержит и слово из таблицы, и слово
    # «работа» в том же предложении — и снимается проверкой, хотя написана правильно.
    # Сузить регекспом не выходит: разница между «слабое поле» (термин) и «слабые
    # допущения» (оценка) смысловая, а не грамматическая.
    #
    # Обороты из таблицы конструкций такой беды не имеют: они срабатывают точно
    # (3 из 3 на образцах роли) — потому что оборот и есть форма оценки.
    # Двусмысленные слова отдаём проверке 3: она смысловая и различит термин от суждения.
    hard = [h for h in res["stop"] if h["kind"] != "слово о работе"]
    res["warn"] = [h for h in res["stop"] if h["kind"] == "слово о работе"]
    res["stop"] = hard
    res["ok"] = (not hard and not res["questions"]
                 and not res["flawless_bad"] and res["uncovered"] == 0)
    return res


if __name__ == "__main__":
    # Самопроверка на образцах из документа роли: пара «за чертой / в границах».
    good = ("Контрольная серия без вращения сделала бы вывод неуязвимым.\n\n"
            "Эта работа пригодится тем, кто измеряет слабые поля на подвижной опоре "
            "(2207.03350, 2022).")
    bad = ("К сожалению, здесь не хватает контрольной серии.\n\n"
           "Что изменится, если убрать вращение?")
    for name, t in (("в границах", good), ("за чертой", bad)):
        r = check_all("", t)
        print(f"{name}: стоп {len(r['stop'])}, вопросов {len(r['questions'])}, "
              f"вердикт {'чисто' if r['ok'] else 'снимаем'}")
        for h in r["stop"]:
            print(f"   {h['kind']}: «{h['found']}»" + (f" — {h.get('why')}" if h.get("why") else ""))
