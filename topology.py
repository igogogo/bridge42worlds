"""Какой формы наше смысловое пространство. Три числа вместо разговора о бутылке Клейна.

Владелец 2026-08-09 просил не отчёт, а разговор — про топологию и кривизну векторного
пространства. Разговор без чисел превращается в красивые слова, поэтому здесь ровно три
вопроса, на каждый из которых можно ответить замером, и каждый ответ что-то меняет
в работе — иначе замер не нужен.

1. СКОЛЬКО У ПРОСТРАНСТВА ИЗМЕРЕНИЙ НА САМОМ ДЕЛЕ.
   Формально их 1024. Но точки не заполняют весь объём: наука — не случайный шум, у неё
   есть устройство, и настоящих степеней свободы гораздо меньше. Это число называется
   внутренней размерностью. Считаем оценкой максимального правдоподобия по расстояниям
   до ближайших соседей (Levina–Bickel): если у точки соседи выстроены как в d-мерном
   шаре, то отношения расстояний до k ближайших выдают d.
   ЗАЧЕМ. Внутренняя размерность — это ответ на вопрос «сколько независимых вопросов
   можно задать корпусу». Если их 12, то карта из 12 осей описывает науку полностью,
   и слепые зоны надо искать в 12 измерениях, а не в 1024.

2. СКОЛЬКО ТОЧЕК ЛЕЖИТ НА КРАЮ.
   Край — это место, где у точки соседи только с одной стороны. У точки в глубине корпуса
   соседи окружают её со всех сторон и их направления гасят друг друга; у точки на краю
   все соседи в одной стороне, и сумма направлений почти не гасится.
   ЗАЧЕМ. Край — это граница исследованного. Работа на краю не окружена похожими, ей
   не с чем сравниться: там либо новизна, либо одиночество ошибки. Ровно тот материал,
   ради которого владелец затевал машину открытий.

3. ЗАМЫКАЮТСЯ ЛИ ПУТИ.
   Если пойти от точки к её соседу, от него к следующему, всё время в одну сторону —
   вернёмся ли мы туда, откуда вышли? В плоском пространстве нет, на сфере да.
   ЗАЧЕМ. Если пути замыкаются, «двигаться в сторону непохожего» бесконечно нельзя:
   уйдя достаточно далеко от астрофизики, мы придём обратно в астрофизику с другой
   стороны. Это меняет саму постановку задачи о слепых зонах — искать надо не «дальше
   всего», а «в дырке», и дырка это другое.

    python topology.py --what ours          наши статьи (3251)
    python topology.py --what arxiv         вспомогательный индекс arXiv
    python topology.py --what both          и сравнить их между собой

ЧЕСТНО О ГРАНИЦАХ. Всё это меряется НА ВЫБОРКЕ и на векторах bge-m3, то есть описывает
не «науку», а её отражение в конкретной модели. Смена модели изменит числа. Поэтому
числа тут — не свойство мира, а свойство нашей нынешней оптики; полезны они ровно
настолько, насколько мы этой оптикой пользуемся.
"""
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
DATA = ROOT / "data"

if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace", line_buffering=True)


def load_ours(limit=0):
    import numpy as np
    vecs, ids = [], []
    # Векторы наших статей лежат в embeddings-articles.jsonl. Рядом есть
    # embeddings-ours.jsonl — это ВЫГРУЗКА НА СЧЁТ (тексты без векторов), не результат;
    # имена похожи, и на этом легко потерять полчаса.
    with (DATA / "embeddings-articles.jsonl").open(encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            r = json.loads(line)
            v = r.get("vec") or r.get("values")
            if v:
                vecs.append(v)
                ids.append(r.get("id", ""))
            if limit and len(vecs) >= limit:
                break
    m = np.asarray(vecs, dtype=np.float32)
    m /= np.linalg.norm(m, axis=1, keepdims=True) + 1e-9
    return m, ids


def load_arxiv(limit=20000):
    import numpy as np
    import vecstore
    ids, m = vecstore.load(DATA / "arxiv")   # порядок именно такой: сначала id, потом векторы
    m = np.asarray(m, dtype=np.float32)
    if limit and len(m) > limit:
        # Прореживаем РАВНОМЕРНО по файлу, а не берём первые N: файл сложен по месяцам,
        # и первые двадцать тысяч — это один месяц, то есть срез моды, а не корпуса.
        step = len(m) // limit
        m, ids = m[::step][:limit], ids[::step][:limit]
    m /= np.linalg.norm(m, axis=1, keepdims=True) + 1e-9
    return m, ids


def knn(M, k):
    """Расстояния и номера k ближайших соседей. Косинус на единичных векторах."""
    import numpy as np
    n = len(M)
    D = np.empty((n, k), dtype=np.float32)
    I = np.empty((n, k), dtype=np.int32)
    CH = 512
    for s in range(0, n, CH):
        sim = M[s:s + CH] @ M.T
        for r in range(len(sim)):
            sim[r, s + r] = -2.0          # сама точка не сосед себе
        idx = np.argpartition(-sim, k, axis=1)[:, :k]
        rows = np.arange(len(sim))[:, None]
        vals = sim[rows, idx]
        o = np.argsort(-vals, axis=1)
        idx = idx[rows, o]
        vals = vals[rows, o]
        I[s:s + CH] = idx
        # Косинус → расстояние. Углы честнее хорд: у оценки размерности расстояние
        # должно расти линейно с удалением, а хорда на больших углах насыщается.
        D[s:s + CH] = np.arccos(np.clip(vals, -1, 1))
    return D, I


def intrinsic_dim(D, k):
    """Оценка Levina–Bickel: d ≈ [ среднее log(r_k / r_j) ]^-1 по j < k.

    Возвращает число, а не список: одно число можно обсуждать, список — нет.

    Устойчивость проверена, а не предположена: на наших статьях при k = 10, 20, 40, 80
    оценка даёт 35,4 · 33,6 · 32,9 · 32,2. Медленный спад с ростом k — известное
    свойство этой оценки, а не шум в данных; разброс в три единицы на восьмикратном
    изменении k означает, что число «около 34» можно обсуждать всерьёз.
    """
    import numpy as np
    r = np.maximum(D[:, :k], 1e-6)
    rk = r[:, -1:]
    with np.errstate(divide="ignore", invalid="ignore"):
        lg = np.log(rk / r[:, :-1])
    lg = np.where(np.isfinite(lg), lg, np.nan)
    mk = np.nanmean(lg, axis=1)
    good = mk > 1e-9
    return float(np.mean(1.0 / mk[good])), int((~good).sum())


def edge_share(M, I, k):
    """Доля точек «на краю»: соседи только с одной стороны — САМЫЙ БОЛЬШОЙ УГЛОВОЙ ЗАЗОР.

    Первая версия этой меры считала длину суммы направлений к соседям: в глубине
    направления гасят друг друга, на краю складываются. На бумаге верно, на наших данных
    бесполезно — она дала «на краю 100% точек». Причина не в корпусе, а в геометрии
    больших размерностей: все векторы bge-m3 лежат в узком конусе (косинус между любыми
    двумя научными текстами положителен), поэтому ни у кого сумма не гасится. Мера
    померила общую анизотропию пространства, а не край корпуса. Число 100% — это всегда
    сигнал, что сломана мера, а не что найдено свойство.

    Здесь другое. Направления к соседям проецируются на СВОЮ локальную плоскость (две
    главные оси окрестности) и смотрится самый большой угловой зазор между ними. Точка
    внутри окружена по всем сторонам — зазоров больше 180° нет. Точка на краю имеет
    пустой полукруг. Тест самокалибрующийся: для двадцати случайных направлений на
    плоскости вероятность зазора >180° примерно 20 / 2^19, то есть четыре сотых процента,
    и ложные срабатывания можно не обсуждать.
    """
    import numpy as np
    n = len(M)
    out = np.empty(n, dtype=np.float32)
    for i in range(n):
        d = M[I[i, :k]] - M[i]
        d = d - d.mean(0)
        # Локальные главные оси: край надо искать в плоскости самой окрестности,
        # а не в осях всего корпуса — у соседей своя ориентация.
        try:
            _, _, vt = np.linalg.svd(d, full_matrices=False)
        except np.linalg.LinAlgError:
            out[i] = 0.0
            continue
        p = (M[I[i, :k]] - M[i]) @ vt[:2].T
        ang = np.sort(np.arctan2(p[:, 1], p[:, 0]))
        gaps = np.diff(np.concatenate([ang, ang[:1] + 2 * np.pi]))
        out[i] = float(gaps.max())
    return out


def loop_closes(M, I, steps=400, seed=42):
    """Идём от точки всё время «вперёд» — вернёмся ли?

    Правило шага: из текущей точки в того соседа, который дальше всех от начала пути.
    Это и есть «одна сторона» на языке соседей. Если пространство замкнуто, расстояние
    до старта сначала растёт, потом начинает падать. Если открыто — выходит на полку.
    """
    import numpy as np
    rng = np.random.default_rng(seed)
    start = int(rng.integers(len(M)))
    cur, path, dist = start, {start}, []
    for _ in range(steps):
        cand = [j for j in I[cur] if j not in path]
        if not cand:
            break
        far = max(cand, key=lambda j: float(np.arccos(np.clip(M[j] @ M[start], -1, 1))))
        cur = far
        path.add(cur)
        dist.append(float(np.arccos(np.clip(M[cur] @ M[start], -1, 1))))
    if not dist:
        return None
    peak = int(np.argmax(dist))
    return {"шагов": len(dist), "макс. удаление": dist[peak], "на шаге": peak + 1,
            "в конце": dist[-1], "вернулись": dist[-1] < dist[peak] * 0.7}


def report(name, M, k):
    import numpy as np
    print(f"\n=== {name}: {len(M)} точек, {M.shape[1]} измерений формально ===")
    D, I = knn(M, k)
    d, bad = intrinsic_dim(D, k)
    print(f"1. Внутренняя размерность: {d:.1f}")
    print(f"   Это значит: независимых «осей смысла» примерно {round(d)}, а не 1024.")
    if bad:
        print(f"   (точек без оценки: {bad} — там соседи совпали до неразличимости)")
    e = edge_share(M, I, k)
    share = float((e > np.pi).mean())
    print(f"2. На краю: {share * 100:.1f}% точек (пустой полукруг среди соседей)")
    print(f"   медиана зазора {np.degrees(np.median(e)):.0f}° · "
          f"p95 {np.degrees(np.quantile(e, 0.95)):.0f}° "
          f"(случайные соседи дали бы {100 * k / 2 ** (k - 1):.2f}%)")
    # Вопрос, который надо задать ДО разговора о крае и о дырках: хватает ли точек,
    # чтобы такой разговор вообще имел смысл. В пространстве размерности d, чтобы у
    # точки были соседи со всех сторон, нужно порядка 2^d точек. Это не придирка:
    # если точек меньше, «пусто вокруг» будет у КАЖДОЙ — и слово «слепая зона»
    # перестаёт что-либо означать.
    need = 2.0 ** d
    per_axis = len(M) ** (1.0 / max(d, 1))
    print(f"   Хватает ли точек: на ось приходится {per_axis:.2f} точки "
          f"(нужно хотя бы 2). Для разговора о дырках в {round(d)} измерениях нужно "
          f"~{need:.0e} точек, у нас {len(M):,}.")
    lp = loop_closes(M, I)
    if lp:
        print(f"3. Путь «всё время от старта»: {lp['шагов']} шагов, "
              f"максимум удаления {lp['макс. удаление']:.3f} рад на шаге {lp['на шаге']}, "
              f"в конце {lp['в конце']:.3f}")
        print(f"   Замкнулся: {'ДА' if lp['вернулись'] else 'НЕТ'}")
    return {"измерений": round(d, 1), "край": round(share, 4), "путь": lp}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--what", default="ours", choices=("ours", "arxiv", "both"))
    ap.add_argument("--k", type=int, default=20)
    ap.add_argument("--limit", type=int, default=20000)
    args = ap.parse_args()

    out = {}
    if args.what in ("ours", "both"):
        M, _ = load_ours()
        out["наши"] = report("НАШИ СТАТЬИ", M, args.k)
    if args.what in ("arxiv", "both"):
        M, _ = load_arxiv(args.limit)
        out["arxiv"] = report("ARXIV (вспомогательный индекс)", M, args.k)
    if len(out) == 2:
        a, b = out["наши"], out["arxiv"]
        print("\n=== сравнение ===")
        print(f"размерность: наши {a['измерений']} · arXiv {b['измерений']}")
        print(f"край:        наши {a['край']*100:.1f}% · arXiv {b['край']*100:.1f}%")
        print("Если у нас размерность заметно НИЖЕ — корпус уже сузился до одной темы,")
        print("и слепые зоны надо искать не внутри него, а по разнице с arXiv.")
    (DATA / "topology.json").write_text(json.dumps(out, ensure_ascii=False, indent=1),
                                        encoding="utf-8")
    print(f"\nчисла записаны в data/topology.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
