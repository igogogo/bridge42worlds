#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Смета на дообучение компаса. Каждое число подписано: замерено или предположено.

Долг с прошлой волны. Смета — тот жанр, где легче всего соврать не цифрой, а тем,
что источник цифры не назван. Поэтому здесь у каждой строки стоит метка:

  ЗАМЕРЕНО   — наше собственное измерение, воспроизводимое;
  УПЁРЛОСЬ   — замер был разрешён и не состоялся; сказано, во что именно;
  ПРАЙС      — цена поставщика, проверяется по его странице;
  СЧИТАНО    — арифметика из строк выше;
  ПРЕДПОЛОЖЕНО — оценка, и она помечена как оценка.

Одно предположение решает половину сметы — пропускная способность обучения. Замер
был разрешён владельцем 19 августа и НЕ СОСТОЯЛСЯ: аренда упёрлась в отсутствие
привязанной оплаты на счету DeepInfra. Подробности в конце, и пока замера нет,
смета показывается вилкой (`--range`), а не одним числом.

    python finetune_estimate.py
    python finetune_estimate.py --pairs 200000 --epochs 3
"""
import argparse
import sys

if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace", line_buffering=True)


def row(mark, text, value=""):
    print(f"  [{mark:<12}] {text:<52} {value}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pairs", type=int, default=200000)
    ap.add_argument("--epochs", type=int, default=3)
    ap.add_argument("--batch", type=int, default=1024)
    ap.add_argument("--seqs-per-sec", type=float, default=400.0,
                    help="последовательностей в секунду на B200, bf16, 512 токенов")
    ap.add_argument("--gpu-hour", type=float, default=3.69)
    ap.add_argument("--range", action="store_true",
                    help="показать разброс сметы по скорости обучения")
    args = ap.parse_args()

    print(f"{'=' * 78}\nСМЕТА НА ДООБУЧЕНИЕ КОМПАСА\n{'=' * 78}\n")

    print("ЧТО ОБУЧАЕМ")
    row("ЗАМЕРЕНО", "модель BAAI/bge-m3, параметров", "568 000 000")
    row("ЗАМЕРЕНО", "LoRA r=16 на Q/K/V/O, обучаемых", "3 145 728")
    row("СЧИТАНО", "доля обучаемых параметров", f"{3145728 / 568e6 * 100:.2f}%")
    row("ЗАМЕРЕНО", "таблица эмбеддингов заморожена, её доля", "45%")
    print()

    print("ДАННЫЕ — БОЛЬШЕ НЕ УЗКОЕ МЕСТО")
    row("ЗАМЕРЕНО", "пар в citations.json", "210 643")
    row("ЗАМЕРЕНО", "из них собрано через Semantic Scholar", "210 408")
    row("ЗАМЕРЕНО", "работ опрошено, чтобы их собрать", "26 191")
    row("ЗАМЕРЕНО", "стоимость сбора", "0 $")
    row("ЗАМЕРЕНО", "аннотации обеих сторон локально", "98% выборки")
    print("\n  Пары строятся из графа цитирований: цитирующая работа и цитируемая —")
    print("  положительная пара. Отрицательные берутся из той же партии (in-batch),")
    print("  отдельно собирать не нужно.")
    print("\n  В прошлой версии сметы здесь стояло «2 102 пары, обучение бессмысленно».")
    print("  Сбор 18 августа закрыл строку f1: 210 643 пары при целевых 200 тысячах.")
    print("  Это замер, а не план — и узким местом стала аренда карты, а не данные.")
    print()

    seqs = args.pairs * 2 * args.epochs
    steps = args.pairs * args.epochs / args.batch
    hours = seqs / args.seqs_per_sec / 3600
    # GradCache считает прямой проход дважды: один раз без графа, чтобы набрать
    # представления всей партии, второй — с графом, по кускам. Это плата за партию
    # 1024 на одной карте, и она примерно удваивает время.
    hours_gc = hours * 1.9
    cost = hours_gc * args.gpu_hour

    print("ОБУЧЕНИЕ")
    row("ПРЕДПОЛОЖЕНО", "эпох", str(args.epochs))
    row("ЗАМЕРЕНО", "партия (in-batch negatives, τ=0.05)", str(args.batch))
    row("СЧИТАНО", "шагов оптимизатора", f"{steps:,.0f}".replace(",", " "))
    row("СЧИТАНО", "последовательностей прогнать",
        f"{seqs:,}".replace(",", " "))
    row("УПЁРЛОСЬ", "пропускная способность, посл./с",
        f"{args.seqs_per_sec:.0f} (замер не состоялся)")
    row("СЧИТАНО", "часов без GradCache", f"{hours:.1f}")
    row("СЧИТАНО", "часов с GradCache (×1.9)", f"{hours_gc:.1f}")
    row("ПРАЙС", "B200 на DeepInfra, за час", f"{args.gpu_hour:.2f} $")
    row("СЧИТАНО", "стоимость одного прогона", f"{cost:.0f} $")
    print()

    print("ПОЛНАЯ СМЕТА")
    runs = 3
    row("ПРЕДПОЛОЖЕНО", "прогонов до приемлемого результата", str(runs))
    row("СЧИТАНО", "обучение, всего", f"{cost * runs:.0f} $")
    row("СЧИТАНО", "сбор данных", "0 $")
    eval_tok = 918297 * 60 / 1e6
    row("СЧИТАНО", "пересчёт поля после обучения, токенов",
        f"{1_556_983 * 60 / 1e6:.0f} млн")
    row("ПРАЙС", "bge-m3 на DeepInfra, за млн токенов", "0.010 $")
    row("СЧИТАНО", "пересчёт поля",
        f"{1_556_983 * 60 / 1e6 * 0.010:.0f} $")
    row("СЧИТАНО", "оценка на контрольной выборке", f"{eval_tok * 0.010:.2f} $")
    total = cost * runs + 1_556_983 * 60 / 1e6 * 0.010 + eval_tok * 0.010
    print(f"\n  {'ИТОГО':<14} {total:.0f} $")
    print(f"  {'из них уже сделано':<14} сбор данных, 0 $ — строка f1 закрыта")
    print(f"  {'упёрлось':<14} аренда карты: к счёту DeepInfra не привязана оплата")
    print()

    print("КРИТЕРИЙ УСПЕХА — ЗАФИКСИРОВАН ДО ОБУЧЕНИЯ")
    row("ЗАМЕРЕНО", "медианный ранг связанной работы сейчас", "2 704 из 918 297")
    row("ЗАМЕРЕНО", "доля в первой сотне сейчас", "11.2%")
    row("ЗАРАНЕЕ", "считаем успехом падение медианного ранга вчетверо", "≤ 676")
    print("\n  Ключ контрольной выборки вскрывается ПОСЛЕ замера, как в прошлый раз.")
    print("  Без этого сравнение до/после ничего не стоит.")
    print()

    print("ПОЧЕМУ ЗАМЕР НЕ СОСТОЯЛСЯ (19 августа)")
    print("  Владелец разрешил потратить до 1 $. Аренда одной B200 на DeepInfra")
    print("  существует и стоит подходяще: конфигурация 1xB200-180GB прошла проверку")
    print("  API, цена 3.69 $/час, тарификация поминутная — десять минут это 0.61 $.")
    print("  Создание контейнера отвечает 402: «missing payment method or suspended».")
    print("  К счёту DeepInfra не привязан способ оплаты; предоплаченных средств,")
    print("  которыми идут вызовы моделей, для аренды карт не хватает.")
    print("  Уходить к другому поставщику запрещено условием задачи, и это верно:")
    print("  новый счёт ради одного замера — не тот размен.")
    print("  Не потрачено ничего, контейнеров не создано.")
    print()
    print("  ЧТО РАЗБЛОКИРУЕТ: привязать карту к счёту DeepInfra. После этого")
    print("  bench_lora.py даёт число за десять минут, и строка «обучение» становится")
    print(f"  ЗАМЕРЕНО. Стоимость самой проверки: {args.gpu_hour / 6:.2f} $")
    print()
    print("  ПОКА ЗАМЕРА НЕТ, честнее вилка, чем одно число: python "
          "finetune_estimate.py --range")

    if args.range:
        print(f"\n{'=' * 78}")
        print("РАЗБРОС СМЕТЫ ПО СКОРОСТИ — то, чего стоит незакрытое предположение")
        print(f"{'=' * 78}")
        print(f"  {'посл./с':>9}{'ч на прогон':>14}{'$ за прогон':>13}"
              f"{'$ за три':>11}   комментарий")
        for sps, note in ((100, "если карта втрое медленнее ожидаемого"),
                          (200, "осторожная оценка"),
                          (400, "нынешнее предположение"),
                          (800, "если длины короче 512 токенов"),
                          (1600, "верхняя граница для B200 на такой модели")):
            h = seqs / sps / 3600 * 1.9
            print(f"  {sps:>9}{h:>14.1f}{h * args.gpu_hour:>13.0f}"
                  f"{h * args.gpu_hour * runs:>11.0f}   {note}")
        print("\n  То есть обучение стоит от 5 до 70 $ в зависимости от одного числа,")
        print("  которого у нас нет. Именно поэтому замер за 0.61 $ окупается сразу.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
