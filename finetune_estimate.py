#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Смета на дообучение компаса. Каждое число подписано: замерено или предположено.

Долг с прошлой волны. Смета — тот жанр, где легче всего соврать не цифрой, а тем,
что источник цифры не назван. Поэтому здесь у каждой строки стоит метка:

  ЗАМЕРЕНО   — наше собственное измерение, воспроизводимое;
  ПРАЙС      — цена поставщика, проверяется по его странице;
  СЧИТАНО    — арифметика из строк выше;
  ПРЕДПОЛОЖЕНО — оценка. Таких строк здесь три, и все три помечены. Одна из них
                 (пропускная способность обучения) решает половину сметы, и её
                 можно превратить в замер за десять минут на арендованной карте —
                 как это сделать, написано в конце.

    python finetune_estimate.py
    python finetune_estimate.py --pairs 200000 --epochs 3
"""
import argparse
import sys

if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace", line_buffering=True)


def row(mark, text, value=""):
    print(f"  [{mark:<12}] {text:<52} {value}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pairs", type=int, default=200000)
    ap.add_argument("--epochs", type=int, default=3)
    ap.add_argument("--batch", type=int, default=1024)
    ap.add_argument("--seqs-per-sec", type=float, default=400.0,
                    help="последовательностей в секунду на B200, bf16, 512 токенов")
    ap.add_argument("--gpu-hour", type=float, default=3.69)
    args = ap.parse_args()

    print(f"{'=' * 78}\nСМЕТА НА ДООБУЧЕНИЕ КОМПАСА\n{'=' * 78}\n")

    print("ЧТО ОБУЧАЕМ")
    row("ЗАМЕРЕНО", "модель BAAI/bge-m3, параметров", "568 000 000")
    row("ЗАМЕРЕНО", "LoRA r=16 на Q/K/V/O, обучаемых", "3 145 728")
    row("СЧИТАНО", "доля обучаемых параметров", f"{3145728 / 568e6 * 100:.2f}%")
    row("ЗАМЕРЕНО", "таблица эмбеддингов заморожена, её доля", "45%")
    print()

    print("ДАННЫЕ — ЗДЕСЬ УЗКОЕ МЕСТО, А НЕ В ВЫЧИСЛЕНИЯХ")
    row("ЗАМЕРЕНО", "пар в citations.json сейчас", "2 102")
    row("ПРЕДПОЛОЖЕНО", "нужно пар для сдвига медианного ранга вчетверо",
        f"{args.pairs:,}".replace(",", " "))
    row("ПРАЙС", "Semantic Scholar API, цена", "0 $ (ключ бесплатный)")
    row("ПРЕДПОЛОЖЕНО", "работ опросить, чтобы собрать пары", "~50 000")
    row("СЧИТАНО", "время сбора при 10 запросах в секунду", "~1.5 часа")
    row("ЗАМЕРЕНО", "аннотации для обеих сторон пары уже локально",
        "4.2 ГБ, 444 месяца")
    print("\n  Пары строятся из графа цитирований: цитирующая работа и цитируемая —")
    print("  положительная пара. Отрицательные берутся из той же партии (in-batch),")
    print("  отдельно собирать не нужно. Пока пар 2 102, обучение бессмысленно:")
    print("  на таком объёме LoRA переобучится за считанные шаги.")
    print()

    seqs = args.pairs * 2 * args.epochs
    steps = args.pairs * args.epochs / args.batch
    hours = seqs / args.seqs_per_sec / 3600
    # GradCache считает прямой проход дважды: один раз без графа, чтобы набрать
    # представления всей партии, второй — с графом, по кускам. Это плата за партию
    # 1024 на одной карте, и она примерно удваивает время.
    hours_gc = hours * 1.9
    cost = hours_gc * args.gpu_hour

    print("ОБУЧЕНИЕ")
    row("ПРЕДПОЛОЖЕНО", "эпох", str(args.epochs))
    row("ЗАМЕРЕНО", "партия (in-batch negatives, τ=0.05)", str(args.batch))
    row("СЧИТАНО", "шагов оптимизатора", f"{steps:,.0f}".replace(",", " "))
    row("СЧИТАНО", "последовательностей прогнать",
        f"{seqs:,}".replace(",", " "))
    row("ПРЕДПОЛОЖЕНО", "пропускная способность, посл./с",
        f"{args.seqs_per_sec:.0f}")
    row("СЧИТАНО", "часов без GradCache", f"{hours:.1f}")
    row("СЧИТАНО", "часов с GradCache (×1.9)", f"{hours_gc:.1f}")
    row("ПРАЙС", "B200 на DeepInfra, за час", f"{args.gpu_hour:.2f} $")
    row("СЧИТАНО", "стоимость одного прогона", f"{cost:.0f} $")
    print()

    print("ПОЛНАЯ СМЕТА")
    runs = 3
    row("ПРЕДПОЛОЖЕНО", "прогонов до приемлемого результата", str(runs))
    row("СЧИТАНО", "обучение, всего", f"{cost * runs:.0f} $")
    row("СЧИТАНО", "сбор данных", "0 $")
    eval_tok = 918297 * 60 / 1e6
    row("СЧИТАНО", "пересчёт поля после обучения, токенов",
        f"{1_556_983 * 60 / 1e6:.0f} млн")
    row("ПРАЙС", "bge-m3 на DeepInfra, за млн токенов", "0.010 $")
    row("СЧИТАНО", "пересчёт поля",
        f"{1_556_983 * 60 / 1e6 * 0.010:.0f} $")
    row("СЧИТАНО", "оценка на контрольной выборке", f"{eval_tok * 0.010:.2f} $")
    total = cost * runs + 1_556_983 * 60 / 1e6 * 0.010 + eval_tok * 0.010
    print(f"\n  {'ИТОГО':<14} {total:.0f} $")
    print(f"  {'на счету':<14} 1.62 $ — то есть сейчас недостижимо целиком,")
    print("                 но сбор данных бесплатен и может идти прямо сейчас.")
    print()

    print("КРИТЕРИЙ УСПЕХА — ЗАФИКСИРОВАН ДО ОБУЧЕНИЯ")
    row("ЗАМЕРЕНО", "медианный ранг связанной работы сейчас", "2 704 из 918 297")
    row("ЗАМЕРЕНО", "доля в первой сотне сейчас", "11.2%")
    row("ЗАРАНЕЕ", "считаем успехом падение медианного ранга вчетверо", "≤ 676")
    print("\n  Ключ контрольной выборки вскрывается ПОСЛЕ замера, как в прошлый раз.")
    print("  Без этого сравнение до/после ничего не стоит.")
    print()

    print("КАК УБРАТЬ ГЛАВНОЕ ПРЕДПОЛОЖЕНИЕ")
    print("  Половина сметы висит на пропускной способности, а она предположена.")
    print("  Убирается за десять минут и полдоллара: арендовать B200 на 10 минут,")
    print("  прогнать 20 шагов на готовых 2 102 парах, замерить секунды на шаг.")
    print("  Тогда вся строка «обучение» станет ЗАМЕРЕНО, и смету можно будет")
    print(f"  показывать владельцу как число, а не как вилку.")
    print(f"  Стоимость самой проверки: {args.gpu_hour / 6:.2f} $")
    return 0


if __name__ == "__main__":
    sys.exit(main())
